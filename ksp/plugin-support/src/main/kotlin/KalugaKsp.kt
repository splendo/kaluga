import org.gradle.api.tasks.SourceTask
import org.gradle.process.CommandLineArgumentProvider
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.plugin.KotlinSourceSet
import org.jetbrains.kotlin.gradle.plugin.KotlinTarget
import java.io.File

private const val METADATA_TARGET = "metadata"
private const val METADATA_KSP_TASK = "kspCommonMainKotlinMetadata"

/**
 * Registers the output of the KSP metadata pass as a `commonMain` source directory, so common code can use what a
 * Kaluga KSP processor generates from the common sources. Call it when the plugin is applied, after the Kotlin
 * Multiplatform and KSP plugins.
 *
 * kotlinter's tasks read every registered source directory, but generated sources are produced output (already
 * formatted by KotlinPoet), so they are excluded from its source: they should be neither linted nor reformatted. The
 * producer dependency kotlinter needs on the generated directory is wired by [addKspProcessor], once the generating KSP
 * task is known, so only that task runs on format/lint rather than every per-target KSP task.
 */
fun Project.registerKspCommonSources() {
    val generatedKspDir = layout.buildDirectory.dir("generated/ksp/metadata/commonMain/kotlin")
    extensions.getByType(KotlinMultiplatformExtension::class.java).apply {
        sourceSets.commonMain { kotlin.srcDir(generatedKspDir) }
    }

    val generatedRoot = layout.buildDirectory.dir("generated").get().asFile.absolutePath
    tasks.matching { it.isKotlinterTask }.configureEach { task ->
        (task as? SourceTask)?.exclude { it.file.absolutePath.startsWith(generatedRoot) }
    }
}

/**
 * Runs the KSP [processor] (a dependency notation) over every pass of this Kotlin Multiplatform project. Call it after
 * the project is evaluated, once its targets are known and any further `commonMain` source directories are registered.
 *
 * The common sources are generated by a single pass: the metadata pass, or with a single target that target's pass.
 * The per-target passes see the common sources too, so the processor gets the `commonSource` and `isSingleTarget`
 * options to skip them there. [additionalCommonSources] are directories the processor should treat as common as well.
 */
fun Project.addKspProcessor(processor: Any, additionalCommonSources: Iterable<File> = emptyList()) {
    val kotlin = extensions.getByType(KotlinMultiplatformExtension::class.java)
    dependencies.add("kspCommonMainMetadata", processor)
    kotlin.targets.configureEach { target ->
        if (target.name != METADATA_TARGET) {
            dependencies.add("ksp${target.name.capitalized()}", processor)
        }
    }
    val leaves = kotlin.targets.filter { it.name != METADATA_TARGET }
    val isSingleTarget = leaves.size == 1

    // kotlinter reads the KSP output registered as a commonMain source dir; that dir is a task output, so Gradle needs
    // an explicit producer dependency. Only the metadata pass (multi-target) or the single leaf pass writes a
    // registered source dir, so depend on just that one. Depending on every KspAATask would force js/wasmJs/macos KSP
    // to run on every formatKotlin/lintKotlin.
    // A leaf's pass is named for its source set on the Android KMP library target, for its compilation otherwise.
    val generatingKspTaskNames = if (isSingleTarget) {
        val leaf = leaves.first().name.capitalized()
        setOf("ksp${leaf}Main", "kspKotlin$leaf")
    } else {
        setOf(METADATA_KSP_TASK)
    }
    tasks.matching { it.isKotlinterTask }.configureEach { task ->
        task.dependsOn(tasks.matching { it.name in generatingKspTaskNames })
    }

    // Multi-target only: order the per-target passes after the common metadata pass so a leaf never races the
    // metadata pass for the same common declarations.
    tasks.withType(KspAATask::class.java).configureEach { task ->
        if (!isSingleTarget && task.name != METADATA_KSP_TASK) {
            task.dependsOn(METADATA_KSP_TASK)
        }
    }
    extensions.getByType(KspExtension::class.java).apply {
        arg(CommonSourceArgumentProvider(files(kotlin.sourceSets.getByName("commonMain").kotlin.sourceDirectories, additionalCommonSources)))
        arg("isSingleTarget", "$isSingleTarget")
    }

    if (isSingleTarget) {
        forceSingleTargetCommonProcessing(kotlin.sourceSets, leaves.first())
    }
}

/**
 * Workaround for KSP's lack of common-source processing in a single-target KMP project (see
 * https://github.com/google/ksp/issues/1525). With one leaf target the `commonMain` metadata compile is named
 * `compileKotlinMetadata`, which KSP unconditionally skips, so no KSP task ever processes `commonMain` and the
 * generated API is never produced. KSP also fails to wire the leaf target's own KSP task for the new
 * Android KMP library target (empty source roots / processor classpath / a disabling `onlyIf`).
 *
 * To make generation work anyway, drive the single leaf target's KSP task directly over the common sources and
 * relocate its output into `commonMain` so common code (and hand-written consumers) can reference the generated API.
 * This is deliberately fragile — it reaches into KSP's task internals — and is only used when the project has a
 * single leaf target; the multi-target path uses the normal `kspCommonMainKotlinMetadata` pass. Currently shaped for
 * the Android leaf (the only single-target case Kaluga produces); a no-op if the leaf's KSP task is absent.
 */
private fun Project.forceSingleTargetCommonProcessing(sourceSets: NamedDomainObjectContainer<KotlinSourceSet>, leaf: KotlinTarget) {
    val leafMain = "${leaf.name}Main"
    val kspTaskName = "ksp${leafMain.capitalized()}"
    if (kspTaskName !in tasks.names) return

    // KSP leaves the leaf's own resolvable processor classpath empty for this target, so build a resolvable view
    // here. Reuse the processor dependency already declared on the leaf target's KSP configuration (`ksp<Target>`)
    // rather than re-stating the coordinate, so the version follows the rest of the plugin.
    val processorClasspath = configurations.detachedConfiguration(
        *configurations.getByName("ksp${leaf.name.capitalized()}").allDependencies.toTypedArray(),
    )
    val leafGenDir = layout.buildDirectory.dir("generated/ksp/${leaf.name}/$leafMain/kotlin")
    val commonRoots = sourceSets.getByName("commonMain").kotlin.srcDirs.filterNot { it.path.contains("generated/ksp") }

    val kspTask = tasks.named(kspTaskName, KspAATask::class.java).get()
    kspTask.kspConfig.sourceRoots.from(commonRoots)
    kspTask.kspConfig.commonSourceRoots.from(commonRoots)
    kspTask.kspConfig.processorClasspath.from(processorClasspath)
    kspTask.kspClasspath.from(processorClasspath)
    kspTask.setOnlyIf { true }

    val leafKotlin = sourceSets.getByName(leafMain).kotlin
    leafKotlin.setSrcDirs(leafKotlin.srcDirs.filterNot { it.path.contains("generated/ksp/${leaf.name}/$leafMain") })
    sourceSets.getByName("commonMain").kotlin.srcDir(leafGenDir)
    tasks.named("compile${leafMain.capitalized()}").configure { it.dependsOn(kspTask) }
}

/**
 * Passes the common source directories to the processor as the `commonSource` option. The directories are declared as
 * a relative-path-sensitive input so the KSP task stays cacheable and relocatable across machines/checkout locations,
 * while the option value handed to the processor remains an absolute path (it is matched against absolute file paths).
 */
internal class CommonSourceArgumentProvider(
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    val commonSources: FileCollection,
) : CommandLineArgumentProvider {
    override fun asArguments(): Iterable<String> = listOf("commonSource=${commonSources.files.joinToString(separator = ":") { it.absolutePath }}")
}

private val org.gradle.api.Task.isKotlinterTask: Boolean get() = name.startsWith("formatKotlin") || name.startsWith("lintKotlin")

private fun String.capitalized(): String = replaceFirstChar { it.uppercaseChar() }
