/**
 * Generates the DATA implementation of a layout tree: a standalone layout, or a sealed root with all its sub-layouts
 * in one file.
 *
 * Properties keep their interface types. Wherever a property type (or a type argument of it) is another layout, it is
 * annotated with that layout's `XData.InterfaceSerializer`, a `KSerializer<X>` whose descriptor is `XData`'s own. That
 * keeps the runtime descriptor identical to the compile-time shape in every position, including invariant ones such
 * as map keys where overriding with the `XData` type is not possible, and lets any implementation of `X` be encoded.
 */
internal class DataGenerator(private val layouts: LayoutIndex) {

    fun generate(root: Layout, dumps: Map<Layout, String>): FileSpec = FileSpec.builder(root.dataClassName)
        .indent("    ")
        .addFileComment("Generated by the Kaluga bytes KSP processor from %L. Do not edit.", root.qualifiedName)
        .apply { tree(root).forEach { addType(dataType(it, dumps.getValue(it))) } }
        .build()

    fun registry(packageName: String, layouts: List<Layout>, prefix: String): FileSpec {
        val name = prefix + REGISTRY
        val entries = layouts.sortedBy { it.qualifiedName }.map { CodeBlock.of("%T.serializer() to %T.LAYOUT_DUMP", it.dataClassName, it.dataClassName) }
        val pair = ClassName("kotlin", "Pair").parameterizedBy(KSERIALIZER.parameterizedBy(STAR), STRING)
        return FileSpec.builder(packageName, name)
            .indent("    ")
            .addType(
                TypeSpec.objectBuilder(name)
                    .addModifiers(KModifier.INTERNAL)
                    .addKdoc("Every DATA layout generated in this package, as its serializer and the layout dump computed at compile time.")
                    .addProperty(
                        PropertySpec.builder("dataLayouts", ClassName("kotlin.collections", "List").parameterizedBy(pair))
                            .initializer(CodeBlock.builder().add("listOf(\n").indent().add(entries.joinToCode(",\n")).unindent().add(",\n)").build())
                            .build(),
                    )
                    .build(),
            )
            .build()
    }

    private fun tree(layout: Layout): List<Layout> = listOf(layout) + layout.sealedChildren.flatMap { tree(it) }

    private fun dataType(layout: Layout, dump: String): TypeSpec {
        val builder = when {
            layout.isSealed -> TypeSpec.interfaceBuilder(layout.dataClassName).addModifiers(KModifier.SEALED)
            layout.properties.isEmpty() -> TypeSpec.objectBuilder(layout.dataClassName).addModifiers(KModifier.DATA)
            else -> TypeSpec.classBuilder(layout.dataClassName).addModifiers(KModifier.DATA)
        }
        if (layout.isInternal) builder.addModifiers(KModifier.INTERNAL)
        builder.addKdoc("The `BytesFormat` DATA implementation of [%T].", layout.interfaceClassName)
        builder.addAnnotation(SERIALIZABLE)
        builder.addAnnotation(AnnotationSpec.builder(SERIAL_NAME).addMember("%S", layout.qualifiedName).build())
        layout.declaration.annotations.filter { it.isSerialInfo() }.forEach { builder.addAnnotation(it.toAnnotationSpec()) }
        if (!layout.isSealed) builder.addSuperinterface(layout.interfaceClassName)
        layout.sealedParent?.let { builder.addSuperinterface(it.dataClassName) }

        val members = mutableListOf<Any>()
        members += PropertySpec.builder("LAYOUT_DUMP", STRING, KModifier.INTERNAL, KModifier.CONST)
            .addKdoc("The layout of [%T] as computed at compile time; `layoutDumpOf(serializer().descriptor)` must return the same.", layout.interfaceClassName)
            .initializer("%L", dump.toStringLiteral())
            .build()
        members += fromFunction(layout)

        when {
            layout.isSealed -> builder.addType(TypeSpec.companionObjectBuilder().addMembers(members).build())

            layout.properties.isEmpty() -> builder.addMembers(members)

            else -> {
                val constructor = FunSpec.constructorBuilder()
                layout.properties.forEach { property ->
                    val type = dataTypeName(property.type)
                    constructor.addParameter(property.name, type)
                    builder.addProperty(
                        PropertySpec.builder(property.name, type, KModifier.OVERRIDE)
                            .mutable(property.isMutable)
                            .initializer(property.name)
                            .addAnnotations(
                                property.annotations.filter {
                                    it.isSerialInfo() || it.qualifiedName() == SERIAL_NAME.canonicalName
                                }.map { it.toAnnotationSpec() }.toList(),
                            )
                            .build(),
                    )
                }
                builder.primaryConstructor(constructor.build())
                builder.addType(TypeSpec.companionObjectBuilder().addMembers(members).build())
            }
        }
        builder.addType(interfaceSerializer(layout))
        return builder.build()
    }

    private fun TypeSpec.Builder.addMembers(members: List<Any>) = apply {
        members.forEach {
            when (it) {
                is PropertySpec -> addProperty(it)
                is FunSpec -> addFunction(it)
            }
        }
    }

    private fun fromFunction(layout: Layout): FunSpec {
        val builder = FunSpec.builder("from")
            .addKdoc("Returns [value] as a [%T], copying it when it is another implementation of [%T].", layout.dataClassName, layout.interfaceClassName)
            .addParameter("value", layout.interfaceClassName)
            .returns(layout.dataClassName)
        when {
            layout.isSealed -> {
                builder.beginControlFlow("return when (value)")
                builder.addStatement("is %T -> value", layout.dataClassName)
                layout.sealedChildren.forEach { builder.addStatement("is %T -> %T.from(value)", it.interfaceClassName, it.dataClassName) }
                builder.endControlFlow()
            }

            layout.properties.isEmpty() -> builder.addStatement("return %T", layout.dataClassName)

            else -> builder.addStatement(
                "return value as? %T ?: %T(%L)",
                layout.dataClassName,
                layout.dataClassName,
                layout.properties.map { CodeBlock.of("%N = value.%N", it.name, it.name) }.joinToCode(", "),
            )
        }
        return builder.build()
    }

    private fun interfaceSerializer(layout: Layout): TypeSpec = TypeSpec.objectBuilder(INTERFACE_SERIALIZER)
        .addKdoc("Serializes any [%T] through the [%T] serializer.", layout.interfaceClassName, layout.dataClassName)
        .addSuperinterface(KSERIALIZER.parameterizedBy(layout.interfaceClassName))
        .addProperty(PropertySpec.builder("descriptor", SERIAL_DESCRIPTOR, KModifier.OVERRIDE).initializer("%T.serializer().descriptor", layout.dataClassName).build())
        .addFunction(
            FunSpec.builder("serialize")
                .addModifiers(KModifier.OVERRIDE)
                .addParameter("encoder", ENCODER)
                .addParameter("value", layout.interfaceClassName)
                .addStatement("%T.serializer().serialize(encoder, %T.from(value))", layout.dataClassName, layout.dataClassName)
                .build(),
        )
        .addFunction(
            FunSpec.builder("deserialize")
                .addModifiers(KModifier.OVERRIDE)
                .addParameter("decoder", DECODER)
                .returns(layout.interfaceClassName)
                .apply {
                    // A sealed DATA interface does not extend the layout interface; every one of its implementations does.
                    if (layout.isSealed) {
                        addStatement("return %T.serializer().deserialize(decoder) as %T", layout.dataClassName, layout.interfaceClassName)
                    } else {
                        addStatement("return %T.serializer().deserialize(decoder)", layout.dataClassName)
                    }
                }
                .build(),
        )
        .build()

    private fun dataTypeName(type: KSType): TypeName {
        val declaration = type.declaration
        val layout = (declaration as? KSClassDeclaration)?.let { layouts[it] }
        if (layout != null) {
            val serializer = AnnotationSpec.builder(SERIALIZABLE).addMember("with = %T.%L::class", layout.dataClassName, INTERFACE_SERIALIZER).build()
            return layout.interfaceClassName.copy(nullable = type.isMarkedNullable, annotations = listOf(serializer))
        }
        val raw = when (declaration) {
            is KSClassDeclaration -> declaration.toClassName()
            else -> throw LayoutDeclarationException("Unsupported type $type", declaration)
        }
        val arguments = type.arguments.map { argument ->
            if (argument.variance == Variance.STAR) STAR else dataTypeName(argument.type!!.resolve())
        }
        return (if (arguments.isEmpty()) raw else raw.parameterizedBy(arguments)).copy(nullable = type.isMarkedNullable)
    }

    private companion object {
        const val INTERFACE_SERIALIZER = "InterfaceSerializer"
        const val REGISTRY = "BytesLayouts"
        val SERIALIZABLE = ClassName("kotlinx.serialization", "Serializable")
        val SERIAL_NAME = ClassName("kotlinx.serialization", "SerialName")
        val KSERIALIZER = ClassName("kotlinx.serialization", "KSerializer")
        val SERIAL_DESCRIPTOR = ClassName("kotlinx.serialization.descriptors", "SerialDescriptor")
        val ENCODER = ClassName("kotlinx.serialization.encoding", "Encoder")
        val DECODER = ClassName("kotlinx.serialization.encoding", "Decoder")
    }
}

/**
 * Re-emits an annotation as source. Arguments equal to their default are left out; a `vararg` argument is written
 * positionally since the annotations that use one take it as their only parameter.
 */
internal fun KSAnnotation.toAnnotationSpec(): AnnotationSpec {
    val declaration = annotationType.resolve().declaration as KSClassDeclaration
    val parameters = declaration.primaryConstructor?.parameters.orEmpty()
    val defaults = defaultArguments.associate { it.name?.asString() to it.value }
    val builder = AnnotationSpec.builder(declaration.toClassName())
    arguments.forEach { argument ->
        val name = argument.name?.asString() ?: return@forEach
        val value = argument.value ?: return@forEach
        if (name in defaults && defaults[name] == value) return@forEach
        val parameter = parameters.firstOrNull { it.name?.asString() == name } ?: return@forEach
        val parameterType = parameter.type.resolve()
        if (parameter.isVararg) {
            builder.addMember((value as List<*>).map { literal(it!!, parameterType) }.joinToCode(", "))
        } else {
            builder.addMember("%N = %L", name, literal(value, parameterType))
        }
    }
    return builder.build()
}

private fun literal(value: Any, type: KSType): CodeBlock {
    if (value is KSAnnotation) return CodeBlock.of("%L", value.toAnnotationSpec())
    val declaration = type.declaration as? KSClassDeclaration ?: throw IllegalArgumentException("Unsupported annotation argument type $type")
    val name = declaration.qualifiedName?.asString()
    primitiveLiteral(value, name)?.let { return it }
    PRIMITIVE_ARRAY_ELEMENTS[name]?.let { element -> return arrayLiteral(value) { primitiveLiteral(it, element)!! } }
    return when (name) {
        "kotlin.reflect.KClass" -> CodeBlock.of(
            "%T::class",
            ((value as? KSType)?.declaration as? KSClassDeclaration)?.toClassName() ?: throw IllegalArgumentException("Unresolved class $value"),
        )

        "kotlin.Array" -> {
            val element = type.arguments.firstOrNull()?.type?.resolve() ?: throw IllegalArgumentException("Unsupported annotation array argument $value")
            arrayLiteral(value) { literal(it, element) }
        }

        else -> when (declaration.classKind) {
            ClassKind.ENUM_CLASS -> CodeBlock.of("%T.%N", declaration.toClassName(), value.enumEntryName())
            else -> throw IllegalArgumentException("Unsupported annotation argument type $name")
        }
    }
}

// The literal of a primitive, unsigned or String annotation argument of the type named [name], or null for another type.
private fun primitiveLiteral(value: Any, name: String?): CodeBlock? {
    val number = value as? Number
    return when (name) {
        "kotlin.Boolean" -> CodeBlock.of("%L", value)

        "kotlin.Byte" -> CodeBlock.of("0x%L.toByte()", (number!!.toInt() and 0xFF).toString(16).uppercase().padStart(2, '0'))

        "kotlin.Short", "kotlin.Int" -> CodeBlock.of("%L", number!!.toInt())

        "kotlin.Long" -> CodeBlock.of("%LL", number!!.toLong())

        "kotlin.Float" -> number!!.toFloat().let { float ->
            when {
                float.isNaN() -> CodeBlock.of("Float.NaN")
                float == Float.POSITIVE_INFINITY -> CodeBlock.of("Float.POSITIVE_INFINITY")
                float == Float.NEGATIVE_INFINITY -> CodeBlock.of("Float.NEGATIVE_INFINITY")
                else -> CodeBlock.of("%Lf", float)
            }
        }

        "kotlin.Double" -> number!!.toDouble().let { double ->
            when {
                double.isNaN() -> CodeBlock.of("Double.NaN")
                double == Double.POSITIVE_INFINITY -> CodeBlock.of("Double.POSITIVE_INFINITY")
                double == Double.NEGATIVE_INFINITY -> CodeBlock.of("Double.NEGATIVE_INFINITY")
                else -> CodeBlock.of("%L", double)
            }
        }

        "kotlin.UByte", "kotlin.UShort", "kotlin.UInt" -> CodeBlock.of("%Lu", value.unsignedString())

        "kotlin.ULong" -> CodeBlock.of("%LuL", value.unsignedString())

        "kotlin.String" -> CodeBlock.of("%S", value)

        "kotlin.Char" -> CodeBlock.of("%L", (value as Char).toCharLiteral())

        else -> null
    }
}

private val PRIMITIVE_ARRAY_ELEMENTS = mapOf(
    "kotlin.BooleanArray" to "kotlin.Boolean",
    "kotlin.ByteArray" to "kotlin.Byte",
    "kotlin.ShortArray" to "kotlin.Short",
    "kotlin.IntArray" to "kotlin.Int",
    "kotlin.LongArray" to "kotlin.Long",
    "kotlin.FloatArray" to "kotlin.Float",
    "kotlin.DoubleArray" to "kotlin.Double",
    "kotlin.CharArray" to "kotlin.Char",
    "kotlin.UByteArray" to "kotlin.UByte",
    "kotlin.UShortArray" to "kotlin.UShort",
    "kotlin.UIntArray" to "kotlin.UInt",
    "kotlin.ULongArray" to "kotlin.ULong",
)

private fun arrayLiteral(value: Any, item: (Any) -> CodeBlock): CodeBlock = (value as? List<*>).orEmpty()
    .map { item(it ?: throw IllegalArgumentException("Unsupported null in annotation array argument $value")) }
    .joinToCode(", ", prefix = "[", suffix = "]")

private fun Char.toCharLiteral(): String = when (this) {
    '\'' -> "'\\''"
    '\\' -> "'\\\\'"
    '\n' -> "'\\n'"
    '\r' -> "'\\r'"
    '\t' -> "'\\t'"
    '\b' -> "'\\b'"
    else -> if (this < ' ' || this > '~') "'\\u%04X'".format(code) else "'$this'"
}

// KotlinPoet's %S drops a trailing line break, which the dump always ends with. Spaces are emitted as KotlinPoet's
// non-wrapping `·` so its line wrapping cannot split the literal.
private fun String.toStringLiteral(): String = buildString {
    append('"')
    this@toStringLiteral.forEach { char ->
        when (char) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '$' -> append("\\$")
            '\n' -> append("\\n")
            ' ' -> append('·')
            else -> append(char)
        }
    }
    append('"')
}

private fun Any.unsignedString(): String = when (this) {
    is ULong -> toString()
    is UInt -> toString()
    is UShort -> toString()
    is UByte -> toString()
    is Long -> toULong().toString()
    is Int -> toUInt().toString()
    is Short -> toUShort().toString()
    is Byte -> toUByte().toString()
    else -> toString()
}

private fun Any.enumEntryName(): String = when (this) {
    is KSType -> declaration.simpleName.asString()
    is KSClassDeclaration -> simpleName.asString()
    else -> toString()
}
