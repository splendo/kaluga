/** The names a generated view reserves for itself, which a layout property cannot use. */
internal val RESERVED_VIEW_PROPERTY_NAMES = setOf("bytes", "sliceBytes", "sliceStart", "sliceLimit", "sliceParent")

internal fun String.capitalized(): String = replaceFirstChar { it.uppercaseChar() }

private fun ByteArray.literal(): CodeBlock = CodeBlock.of("%L", joinToString(", ", prefix = "byteArrayOf(", postfix = ")") { it.literal() })

private fun Byte.literal(): String = (toInt() and 0xFF).let { value -> if (value < 0x80) "0x%02X".format(value) else "0x%02X.toByte()".format(value) }

// Round-trips exactly: the JVM prints the shortest decimal that parses back to the same Double.
private fun Double.literal(): CodeBlock = when {
    isNaN() -> CodeBlock.of("Double.NaN")
    this == Double.POSITIVE_INFINITY -> CodeBlock.of("Double.POSITIVE_INFINITY")
    this == Double.NEGATIVE_INFINITY -> CodeBlock.of("Double.NEGATIVE_INFINITY")
    else -> CodeBlock.of("%L", toString())
}
