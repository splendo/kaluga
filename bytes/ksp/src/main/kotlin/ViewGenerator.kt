/**
 * Generates the VIEW implementation of a layout from its [ViewContext]s: the public `XView` value class over a whole
 * array, and per context an internal `XLayout` object with every accessor as a function of the backing array `b`,
 * the frame start `s` and `lim`, the end of the frame's body (its end minus the postfix), plus an `XSlice` class
 * implementing the layout over a range of a larger array, which nested layouts and `wrapRange` return.
 */
internal class ViewGenerator(private val planner: ViewPlanner) {

    fun generate(layout: Layout): FileSpec {
        if (layout.isSealed) return generateSealed(layout)
        val root = planner.root(layout)!!
        val rootPlan = root.plan!!.getOrThrow()
        return FileSpec.builder(layout.viewClassName)
            .indent("    ")
            .addFileComment("Generated by the Kaluga bytes KSP processor from %L. Do not edit.", layout.qualifiedName)
            .addAnnotation(OPT_IN_INTERNAL)
            .addType(viewType(layout, root, rootPlan))
            .addFunction(toViewFunction(layout))
            .apply {
                planner.plannedContexts(layout).forEach { context ->
                    val plan = context.plan!!.getOrThrow()
                    addType(layoutObject(context, plan))
                    addType(sliceType(context, plan))
                    plan.fields.mapNotNull { it.access as? Access.Collection }.flatMap { it.items }.forEach { addType(itemObject(it)) }
                }
            }
            .build()
    }

    fun registry(packageName: String, layouts: List<Layout>, prefix: String): FileSpec {
        val name = prefix + REGISTRY
        val entry = ClassName(packageName, name, "Entry")
        val entries = layouts.sortedBy { it.qualifiedName }.map { layout ->
            val root = planner.root(layout)!!
            if (layout.isSealed) {
                return@map CodeBlock.of(
                    "%T(%S, { %T.encode(it as %T).bytes }, { bytes, check -> %T.wrap(bytes, check).value }, { bytes, from, to, check -> %T.wrapRange(bytes, from, to, check) }, { %T.toData(it as %T) })",
                    entry,
                    layout.qualifiedName,
                    layout.frameClassName,
                    layout.interfaceClassName,
                    layout.frameClassName,
                    layout.frameClassName,
                    root.layoutName,
                    layout.interfaceClassName,
                )
            }
            val stuffed = root.plan!!.getOrThrow().stuffing != null
            CodeBlock.of(
                if (stuffed) {
                    "%T(%S, { %T.encodeToWire(it as %T) }, { bytes, check -> %T.fromWire(bytes, check) }, { bytes, from, to, check -> %T.wrapRange(bytes, from, to, check) }, { if (it is %T) it.toData() else (it as %T).toData() })"
                } else {
                    "%T(%S, { %T.encode(it as %T).bytes }, { bytes, check -> %T.wrap(bytes, check) }, { bytes, from, to, check -> %T.wrapRange(bytes, from, to, check) }, { if (it is %T) it.toData() else (it as %T).toData() })"
                },
                entry,
                layout.qualifiedName,
                layout.viewClassName,
                layout.interfaceClassName,
                layout.viewClassName,
                layout.viewClassName,
                layout.viewClassName,
                root.sliceName,
            )
        }
        val entryType = TypeSpec.classBuilder(entry)
            .addKdoc(
                "The VIEW of the layout with DATA serial name [serialName], as functions over untyped values; [view] and [wrapRange] validate, checking checksums when asked.\n\n" +
                    "[encode] and [view] use the bytes `BytesFormat` encodes, stuffed for a byte-stuffed layout; [wrapRange] views a frame nested as `BytesFormat` nests it, unstuffed.",
            )
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter("serialName", STRING)
                    .addParameter("encode", LambdaTypeName.get(parameters = arrayOf(ANY), returnType = BYTE_ARRAY))
                    .addParameter("view", LambdaTypeName.get(parameters = arrayOf(BYTE_ARRAY, BOOLEAN), returnType = ANY))
                    .addParameter("wrapRange", LambdaTypeName.get(parameters = arrayOf(BYTE_ARRAY, INT, INT, BOOLEAN), returnType = ANY))
                    .addParameter("toData", LambdaTypeName.get(parameters = arrayOf(ANY), returnType = ANY))
                    .build(),
            )
            .apply {
                listOf(
                    "serialName" to STRING,
                    "encode" to LambdaTypeName.get(parameters = arrayOf(ANY), returnType = BYTE_ARRAY),
                    "view" to LambdaTypeName.get(parameters = arrayOf(BYTE_ARRAY, BOOLEAN), returnType = ANY),
                    "wrapRange" to LambdaTypeName.get(parameters = arrayOf(BYTE_ARRAY, INT, INT, BOOLEAN), returnType = ANY),
                    "toData" to LambdaTypeName.get(parameters = arrayOf(ANY), returnType = ANY),
                ).forEach { (name, type) -> addProperty(PropertySpec.builder(name, type).initializer(name).build()) }
            }
            .build()
        return FileSpec.builder(packageName, name)
            .indent("    ")
            .addType(
                TypeSpec.objectBuilder(name)
                    .addModifiers(KModifier.INTERNAL)
                    .addKdoc("Every layout generated in this package with both DATA and VIEW, keyed by the serial name of its DATA class.")
                    .addType(entryType)
                    .addProperty(
                        PropertySpec.builder("views", ClassName("kotlin.collections", "List").parameterizedBy(entry))
                            .initializer(CodeBlock.builder().add("listOf(\n").indent().add(entries.joinToCode(",\n")).unindent().add(",\n)").build())
                            .build(),
                    )
                    .build(),
            )
            .build()
    }

    private fun viewType(layout: Layout, root: ViewContext, plan: ViewPlan): TypeSpec {
        val view = layout.viewClassName
        val builder = TypeSpec.classBuilder(view)
            .addModifiers(KModifier.VALUE)
            .addAnnotation(JVM_INLINE)
            .addKdoc(
                "The zero-copy VIEW implementation of [%T], reading and writing [bytes] in place.\n\n" +
                    "`==` compares the backing arrays by reference, since a value class cannot override `equals`; use [contentEquals] to compare content.",
                layout.interfaceClassName,
            )
            .addSuperinterface(layout.interfaceClassName)
            .primaryConstructor(FunSpec.constructorBuilder().addParameter("bytes", BYTE_ARRAY).build())
            .addProperty(PropertySpec.builder("bytes", BYTE_ARRAY).initializer("bytes").build())
        if (layout.isInternal) builder.addModifiers(KModifier.INTERNAL)
        val stuffing = plan.stuffing
        if (stuffing != null) {
            builder.addKdoc(
                "\n\n[bytes] hold the frame unstuffed, as it is read and written in place; [toWire] and [fromWire] convert it from and to the " +
                    "stuffed bytes `BytesFormat` encodes and decodes.",
            )
        }
        val rootArguments = rootArguments(plan, "bytes")
        val arguments = CodeBlock.of("bytes, ${rootArguments.start}, %L", rootArguments.limit)
        val checksummed = plan.hasChecksums()
        val update = CodeBlock.of("%T.updateChecksums(%L)", root.layoutName, arguments)
        plan.fields.forEach {
            builder.addProperty(overrideProperty(it, root, arguments, if (checksummed) CodeBlock.of("%T { %L }", VIEW_PARENT, update) else null, update.takeIf { checksummed }))
        }
        builder.addFunction(
            FunSpec.builder("validate")
                .addKdoc("Checks these bytes the way `BytesFormat` decodes them, throwing its exception for the first problem found.")
                .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                .addStatement("%T.validate(%L, validateChecksum)", root.layoutName, arguments)
                .build(),
        )
        if (checksummed) {
            builder.addFunction(
                FunSpec.builder("isChecksumValid")
                    .addKdoc("Whether every checksum in these bytes matches; like [validate], it throws for anything else wrong.")
                    .returns(BOOLEAN)
                    .beginControlFlow("return try")
                    .addStatement("%T.validate(%L, true)", root.layoutName, arguments)
                    .addStatement("true")
                    .nextControlFlow("catch (e: %T)", INVALID_CHECKSUM)
                    .addStatement("false")
                    .endControlFlow()
                    .build(),
            )
            builder.addFunction(
                FunSpec.builder("edit")
                    .addKdoc("Runs [block] on this view, updating the checksums once afterwards instead of after every write.")
                    .addParameter("block", LambdaTypeName.get(receiver = root.sliceName, returnType = UNIT))
                    .addStatement("%T(%L, %T).block()", root.sliceName, arguments, VIEW_BATCH)
                    .addStatement("%L", update)
                    .build(),
            )
        }
        if (Generate.DATA in layout.generate) {
            builder.addFunction(
                FunSpec.builder("toData")
                    .addKdoc("Copies this view into a [%T].", layout.dataClassName)
                    .returns(layout.dataClassName)
                    .addStatement("return %T.toData(%L)", root.layoutName, arguments)
                    .build(),
            )
        }
        builder.addFunction(
            FunSpec.builder("contentEquals")
                .addKdoc("Whether [other] is a view of [%T] holding the same bytes.", layout.interfaceClassName)
                .addParameter("other", layout.interfaceClassName)
                .returns(BOOLEAN)
                .addStatement("return %T.contentEquals(%L, other)", root.layoutName, arguments)
                .build(),
        )
        builder.addFunction(
            FunSpec.builder("contentHashCode")
                .addKdoc("A hash of the bytes of this view, consistent with [contentEquals].")
                .returns(INT)
                .addStatement("return %T.contentHashCode(%L)", root.layoutName, arguments)
                .build(),
        )
        builder.addFunction(
            FunSpec.builder("toString").addModifiers(KModifier.OVERRIDE).returns(STRING)
                .addStatement("return %T.describe(%S, %L)", root.layoutName, view.simpleName, arguments)
                .build(),
        )
        val framing = CodeBlock.of("%L, %L", plan.prefix?.size ?: 0, plan.postfix?.size ?: 0)
        if (stuffing != null) {
            builder.addFunction(
                FunSpec.builder("toWire")
                    .addKdoc("A new array with these bytes as `BytesFormat` encodes them: stuffed between the prefix and the postfix.")
                    .returns(BYTE_ARRAY)
                    .addStatement("return %T.toWire(bytes, %L, $WIRE_STUFFING)", VIEW_STUFFING, framing)
                    .build(),
            )
        }
        val parameters = plan.fields.map { it.name to it.typeName() }
        val staticSize = plan.staticSize
        val companion = TypeSpec.companionObjectBuilder()
        if (staticSize != null) {
            companion.addProperty(
                PropertySpec.builder("SIZE_BYTES", INT, KModifier.CONST)
                    .addKdoc("The size of every [%T] in bytes.", view)
                    .initializer("%L", staticSize)
                    .build(),
            )
        }
        val stuffedFrame = plan.hasStuffed()
        fun FunSpec.Builder.encodeBody(size: CodeBlock, write: CodeBlock) = apply {
            if (staticSize != null) {
                addStatement("return %T(%T(%L).also { %L })", view, BYTE_ARRAY, staticSize, write)
            } else {
                if (stuffedFrame) addStatement("val $CONTENTS = %T()", VIEW_CONTENTS)
                addStatement("val size = %L", size)
                addStatement("return %T(%T(size).also { %L })", view, BYTE_ARRAY, write)
            }
        }
        val contents = contentsArgument(stuffedFrame)
        // A new frame fills its array: it starts at the array's start, or ends at its end when mirrored.
        val size = staticSize?.let { CodeBlock.of("%L", it) } ?: CodeBlock.of("size")
        val writeArguments = if (plan.mirrored) {
            CodeBlock.of("it, %L, %L", size, plan.footer)
        } else {
            CodeBlock.of("it, 0, %L", if (plan.footer == 0) size else CodeBlock.of("%L - %L", size, plan.footer))
        }
        companion.addFunction(
            FunSpec.builder("encode")
                .addKdoc("Encodes [value] into a new [%T].", view)
                .addParameter("value", layout.interfaceClassName)
                .returns(view)
                .encodeBody(CodeBlock.of("%T.sizeOf(value$contents)", root.layoutName), CodeBlock.of("%T.write(%L, value$contents)", root.layoutName, writeArguments))
                .build(),
        )
        val values = parameters.map { CodeBlock.of("%N", it.first) }.joinToCode(", ")
        companion.addFunction(
            FunSpec.builder("invoke")
                .addModifiers(KModifier.OPERATOR)
                .addKdoc("Encodes a new [%T] from its property values.", view)
                .apply { parameters.forEach { (name, type) -> addParameter(name, type) } }
                .returns(view)
                .encodeBody(
                    CodeBlock.of("%T.sizeOfValues(%L$contents)", root.layoutName, values),
                    CodeBlock.of(
                        "%T.writeValues(%L$contents)",
                        root.layoutName,
                        (
                            listOf(writeArguments) + parameters.map {
                                CodeBlock.of("%N", it.first)
                            }
                            ).joinToCode(", "),
                    ),
                )
                .build(),
        )
        companion.addFunction(
            FunSpec.builder("wrap")
                .addKdoc("A view of [bytes], checked first as `BytesFormat` checks what it decodes; the constructor checks nothing.")
                .addParameter("bytes", BYTE_ARRAY)
                .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                .returns(view)
                .addStatement("%T.validate(%L, validateChecksum)", root.layoutName, arguments)
                .addStatement("return %T(bytes)", view)
                .build(),
        )
        if (stuffing != null) {
            companion.addProperty(PropertySpec.builder(WIRE_STUFFING, STUFFING_SCHEME, KModifier.PRIVATE).initializer("%L", scheme(stuffing)).build())
            companion.addFunction(
                FunSpec.builder("fromWire")
                    .addKdoc("A view of the frame the stuffed [wire] bytes hold, unstuffed into a new array and checked like [wrap].")
                    .addParameter("wire", BYTE_ARRAY)
                    .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                    .returns(view)
                    .addStatement("return wrap(%T.fromWire(wire, %L, $WIRE_STUFFING), validateChecksum)", VIEW_STUFFING, framing)
                    .build(),
            )
            companion.addFunction(
                FunSpec.builder("encodeToWire")
                    .addKdoc("Encodes [value] as `BytesFormat` does, stuffed.")
                    .addParameter("value", layout.interfaceClassName)
                    .returns(BYTE_ARRAY)
                    .addStatement("return encode(value).toWire()")
                    .build(),
            )
        }
        companion.addFunction(
            FunSpec.builder("wrapRange")
                .addKdoc("A view of [%T] over `[from, to)` of [bytes], checked first like [wrap], reading and writing it in place.", layout.interfaceClassName)
                .addParameter("bytes", BYTE_ARRAY)
                .addParameter("from", INT)
                .addParameter("to", INT)
                .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                .returns(layout.interfaceClassName)
                .addStatement("%T.checkWrapRange(bytes, from, to)", VIEW_BYTES)
                .addStatement("%T.validate(bytes, %L, %L, validateChecksum)", root.layoutName, rangeArguments(plan).start, rangeArguments(plan).limit)
                .addStatement("return %T(bytes, %L, %L)", root.sliceName, rangeArguments(plan).start, rangeArguments(plan).limit)
                .build(),
        )
        return builder.addType(companion.build()).build()
    }

    private fun toViewFunction(layout: Layout): FunSpec = FunSpec.builder("to${layout.viewClassName.simpleName}")
        .addKdoc("This value as a [%T]: itself when it already is one, otherwise a new encoding of it.", layout.viewClassName)
        .receiver(layout.interfaceClassName)
        .returns(layout.viewClassName)
        .apply { if (layout.isInternal) addModifiers(KModifier.INTERNAL) }
        .addStatement("return this as? %T ?: %T.encode(this)", layout.viewClassName, layout.viewClassName)
        .build()

    private fun FieldPlan.typeName(): TypeName = value.typeName.copy(nullable = nullable)

    /**
     * A property of a view or slice. A layout nested in it is given [parent] so it can report writes, and [afterSet]
     * runs after every write, both only when there is a checksum to keep up to date.
     */
    private fun overrideProperty(field: FieldPlan, context: ViewContext, arguments: CodeBlock, parent: CodeBlock?, afterSet: CodeBlock?): PropertySpec {
        val name = field.name.capitalized()
        val getterArguments = if (parent != null && field.access.takesParent()) CodeBlock.of("%L, %L", arguments, parent) else arguments
        return PropertySpec.builder(field.name, field.typeName(), KModifier.OVERRIDE)
            .mutable(field.settable)
            .getter(FunSpec.getterBuilder().addStatement("return %T.get$name(%L)", context.layoutName, getterArguments).build())
            .apply {
                if (field.settable) {
                    setter(
                        FunSpec.setterBuilder().addParameter("value", field.typeName())
                            .addStatement("%T.set$name(%L, value)", context.layoutName, arguments)
                            .apply { afterSet?.let { addStatement("%L", it) } }
                            .build(),
                    )
                }
            }
            .build()
    }

    private fun sliceType(context: ViewContext, plan: ViewPlan): TypeSpec {
        val layout = context.layout
        val builder = TypeSpec.classBuilder(context.sliceName)
            .addKdoc(
                "A view of [%T] over part of a larger array, as nested layouts and `wrapRange` return it; cast to it to write a nested layout's properties in place.",
                layout.interfaceClassName,
            )
            .addSuperinterface(layout.interfaceClassName)
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addModifiers(KModifier.INTERNAL)
                    .addParameter(SLICE_BYTES, BYTE_ARRAY)
                    .addParameter(SLICE_START, INT)
                    .addParameter(SLICE_LIMIT, INT)
                    .addParameter(ParameterSpec.builder(SLICE_PARENT, VIEW_PARENT.copy(nullable = true)).defaultValue("null").build())
                    .build(),
            )
            .addProperty(PropertySpec.builder(SLICE_BYTES, BYTE_ARRAY, KModifier.INTERNAL).initializer(SLICE_BYTES).build())
            .addProperty(PropertySpec.builder(SLICE_START, INT, KModifier.INTERNAL).initializer(SLICE_START).build())
            .addProperty(PropertySpec.builder(SLICE_LIMIT, INT, KModifier.INTERNAL).initializer(SLICE_LIMIT).build())
            .addProperty(PropertySpec.builder(SLICE_PARENT, VIEW_PARENT.copy(nullable = true), KModifier.INTERNAL).initializer(SLICE_PARENT).build())
        val arguments = CodeBlock.of("$SLICE_BYTES, $SLICE_START, $SLICE_LIMIT")
        val checksummed = plan.hasChecksums()
        // In an edit block (a ViewBatch parent) the checksums are updated once at the end instead.
        builder.addFunction(
            FunSpec.builder("changed").addModifiers(KModifier.PRIVATE)
                .beginControlFlow("if ($SLICE_PARENT !== %T)", VIEW_BATCH)
                .apply { if (checksummed) addStatement("%T.updateChecksums(%L)", context.layoutName, arguments) }
                .addStatement("$SLICE_PARENT?.changed()")
                .endControlFlow()
                .build(),
        )
        builder.addFunction(
            FunSpec.builder("childParent").addModifiers(KModifier.PRIVATE).returns(VIEW_PARENT.copy(nullable = true))
                .addStatement(if (checksummed) "return if ($SLICE_PARENT === %T) $SLICE_PARENT else %T { changed() }" else "return $SLICE_PARENT", VIEW_BATCH, VIEW_PARENT)
                .build(),
        )
        plan.fields.forEach { builder.addProperty(overrideProperty(it, context, arguments, CodeBlock.of("childParent()"), CodeBlock.of("changed()"))) }
        if (layout.isInternal) builder.addModifiers(KModifier.INTERNAL)
        if (Generate.DATA in layout.generate) {
            builder.addFunction(
                FunSpec.builder("toData").addKdoc("Copies this view into a [%T].", layout.dataClassName).returns(layout.dataClassName)
                    .addStatement("return %T.toData(%L)", context.layoutName, arguments)
                    .build(),
            )
        }
        builder.addFunction(
            FunSpec.builder("equals").addModifiers(KModifier.OVERRIDE).addParameter("other", ANY.copy(nullable = true)).returns(BOOLEAN)
                .addStatement("return other is %T && %T.contentEquals(%L, other)", context.sliceName, context.layoutName, arguments)
                .build(),
        )
        builder.addFunction(
            FunSpec.builder("hashCode").addModifiers(KModifier.OVERRIDE).returns(INT)
                .addStatement("return %T.contentHashCode(%L)", context.layoutName, arguments)
                .build(),
        )
        builder.addFunction(
            FunSpec.builder("toString").addModifiers(KModifier.OVERRIDE).returns(STRING)
                .addStatement("return %T.describe(%S, %L)", context.layoutName, context.sliceName.simpleName, arguments)
                .build(),
        )
        return builder.build()
    }

    /**
     * Adds what every frame object has: its constants, a getter (and a setter when in place is possible) per value,
     * the anchors positions after a varying value depend on, `sizeOfValues`, `writeValues` and `end`.
     */
    private fun addFrameMembers(builder: TypeSpec.Builder, plan: ViewPlan, item: Boolean = false) {
        val frame = FrameCode(plan)
        val staticSize = plan.staticSize
        if (staticSize != null) builder.addProperty(PropertySpec.builder("SIZE", INT, KModifier.CONST).initializer("%L", staticSize).build())
        plan.prefix?.let { builder.addProperty(byteArrayConstant(FRAME_PREFIX, it)) }
        plan.postfix?.let { builder.addProperty(byteArrayConstant(FRAME_POSTFIX, it)) }
        plan.checksum?.let { builder.addProperty(checksumConstant(FRAME_CHECKSUM, it)) }
        plan.fields.forEach { field -> constants(field).forEach { builder.addProperty(it) } }
        plan.fields.filter { (it.access as? Access.Collection)?.count is Count.Stuffed }.forEach { builder.addFunction(stuffedContent(it)) }

        plan.fields.forEach { field ->
            val name = field.name.capitalized()
            val getter = bufferFunction("get$name").returns(field.typeName())
            if (field.access.takesParent()) getter.addParameter(ParameterSpec.builder(PARENT, VIEW_PARENT.copy(nullable = true)).defaultValue("null").build())
            field.presence?.let { getter.addStatement("if (!(%L)) return null", frame.presence(it)) }
            val access = field.access
            if (access is Access.Collection) {
                collectionGetter(getter, field, access, frame)
            } else {
                getter.addStatement("return %L", read(field, access, frame.location(field)))
            }
            builder.addFunction(getter.build())
            if (field.settable) {
                builder.addFunction(
                    bufferFunction("set$name").addParameter("value", field.typeName())
                        .apply { write(field, field.access, frame.location(field), unwrap(field.value, CodeBlock.of("value"))).forEach { addStatement("%L", it) } }
                        .build(),
                )
            }
            field.end?.let { end ->
                val function = bufferFunction("endOf$name").addModifiers(KModifier.PRIVATE).returns(INT)
                function.addStatement("val start = %L", frame.bits(field.start))
                field.presence?.let { function.addStatement("if (!(%L)) return start", frame.presence(it)) }
                val pos = CodeBlock.of(if (plan.mirrored) "s - %T.alignBits(start) / 8" else "s + %T.alignBits(start) / 8", VIEW_BYTES)
                when (val access = field.access) {
                    is Access.BodyBit -> function.addStatement("return start + 1")

                    is Access.Collection -> collectionEnd(function, field, access, pos, plan.mirrored)

                    is Access.Sealed -> function.addStatement("return (%T.end(b, %L, %L) - s) * 8", access.context.layoutName, pos, sealedLimit(access))

                    is Access.EnumTable -> if (access.fixedBytes == null) {
                        function.addStatement(
                            "return %T.alignBits(start) + (%L + %N[%T.matchIndex(b, %L + %L, %N, lim)].size) * 8",
                            VIEW_BYTES,
                            (access.prefix?.size ?: 0) + (access.postfix?.size ?: 0),
                            "${field.name}Table",
                            VIEW_BYTES,
                            pos,
                            access.prefix?.size ?: 0,
                            "${field.name}Table",
                        )
                    } else {
                        function.addStatement("return %T.alignBits(start) + %L", VIEW_BYTES, fixedContentBytes(access) * Byte.SIZE_BITS)
                    }

                    is Access.Nested -> function.addStatement("return (%T.end(b, %L, %L) - s) * 8", access.context.layoutName, pos, nestedLimit(access, pos))

                    is Access.Text -> function.addStatement(
                        "return %T.alignBits(start) + %T.%N(b, %L, lim, %N) * 8",
                        VIEW_BYTES,
                        VIEW_STRINGS,
                        if (plan.mirrored) "sizeDown" else "size",
                        pos,
                        "${field.name}String",
                    )

                    else -> if ((access as? Access.Number)?.width is Width.Selected) {
                        function.addStatement("return %T.alignBits(start) + %L * 8", VIEW_BYTES, contentBytes(field, access))
                    } else {
                        function.addStatement("return %T.alignBits(start) + %L", VIEW_BYTES, fixedContentBytes(access) * Byte.SIZE_BITS)
                    }
                }
                check(end.name == field.name)
                builder.addFunction(function.build())
            }
        }

        val valueNames = plan.fields.associateWith { field -> field.name.let { name -> if (name in BUFFER_PARAMETERS) "${name}Value" else name } }
        val sizeOfValues = FunSpec.builder("sizeOfValues").returns(INT)
        plan.fields.forEach { sizeOfValues.addParameter(valueNames.getValue(it), it.typeName()) }
        if (plan.hasStuffed()) sizeOfValues.addParameter(contentsParameter())
        if (staticSize != null) {
            sizeOfValues.addStatement("return SIZE")
        } else {
            val walk = Walk(sizeOfValues, plan.headerStart + plan.headerBits, dry = true, mirrored = plan.mirrored)
            walk(walk, plan, valueNames)
            sizeOfValues.addStatement("return %L", walk.endBytes(plan.footer))
        }
        builder.addFunction(sizeOfValues.build())
        val writeValues = bufferFunction("writeValues")
            .addKdoc("Writes the frame of these values at [s], returning where it ends.")
            .returns(INT)
        plan.fields.forEach { writeValues.addParameter(valueNames.getValue(it), it.typeName()) }
        if (plan.hasStuffed()) writeValues.addParameter(contentsParameter())
        // A frame of a varying size is only ever written into a new array, so only one of a fixed size can be rewritten.
        if (staticSize != null) writeValues.addStatement(if (plan.mirrored) "%T.clear(b, s - SIZE, s)" else "%T.clear(b, s, s + SIZE)", VIEW_BYTES)
        if (plan.prefix != null) {
            if (plan.mirrored) {
                writeValues.addStatement("%T.write(b, s - %L, %N, b.size)", VIEW_BYTES, plan.prefix.size, FRAME_PREFIX)
            } else {
                writeValues.addStatement("%T.write(b, s, %N, lim)", VIEW_BYTES, FRAME_PREFIX)
            }
        }
        val walk = Walk(writeValues, plan.headerStart + plan.headerBits, dry = false, mirrored = plan.mirrored)
        walk(walk, plan, valueNames)
        writeValues.addStatement("val $BODY_END = %L", walk.endPos())
        val bodyEnd = CodeBlock.of(BODY_END)
        frameChecksum(plan, bodyEnd, "update")?.let { writeValues.addStatement("%L", it) }
        if (plan.postfix != null) {
            val crc = plan.checksum?.crc?.byteWidth ?: 0
            if (plan.mirrored) {
                writeValues.addStatement("%T.write(b, %L - %L, %N, b.size)", VIEW_BYTES, bodyEnd, crc + plan.postfix.size, FRAME_POSTFIX)
            } else {
                writeValues.addStatement("%T.write(b, %L + %L, %N, lim + %L)", VIEW_BYTES, bodyEnd, crc, FRAME_POSTFIX, plan.footer)
            }
        }
        writeValues.addStatement(
            if (plan.footer == 0) {
                "return $BODY_END"
            } else if (plan.mirrored) {
                "return $BODY_END - %L"
            } else {
                "return $BODY_END + %L"
            },
            plan.footer,
        )
        builder.addFunction(writeValues.build())
        if (plan.hasChecksums()) builder.addFunction(updateChecksums(plan, frame))
        builder.addFunction(validate(plan, frame))
        builder.addFunction(
            bufferFunction("end")
                .apply { if (item) addModifiers(KModifier.OVERRIDE) }
                .addKdoc("The end of the frame starting at [s], following the flag header like the decoder does.")
                .returns(INT)
                .addStatement(
                    if (staticSize !=
                        null
                    ) {
                        if (plan.mirrored) "return s - SIZE" else "return s + SIZE"
                    } else {
                        "return %L"
                    },
                    frame.bytePos(plan.bodyEnd).let { if (plan.footer == 0) it else CodeBlock.of(if (plan.mirrored) "%L - %L" else "%L + %L", it, plan.footer) },
                )
                .build(),
        )
    }

    private fun layoutObject(context: ViewContext, plan: ViewPlan): TypeSpec {
        val layout = context.layout
        val staticSize = plan.staticSize
        val builder = TypeSpec.objectBuilder(context.layoutName)
            .addModifiers(KModifier.INTERNAL)
            .addKdoc("The accessors of [%T] as compiled here: property functions take the array, the frame start and the end of the body.", layout.interfaceClassName)
        addFrameMembers(builder, plan)
        val stuffed = plan.hasStuffed()
        val values = plan.fields.map { CodeBlock.of("value.%N", it.name) } + listOfNotNull(CodeBlock.of(CONTENTS).takeIf { stuffed })
        builder.addFunction(
            FunSpec.builder("sizeOf").addParameter("value", layout.interfaceClassName).returns(INT)
                .apply { if (stuffed) addParameter(contentsParameter()) }
                .addStatement(if (staticSize != null) "return SIZE" else "return sizeOfValues(%L)", values.joinToCode(", "))
                .build(),
        )

        builder.addFunction(
            bufferFunction("write")
                .addParameter("value", layout.interfaceClassName)
                .apply { if (stuffed) addParameter(contentsParameter()) }
                .returns(INT)
                .addStatement("return writeValues(%L)", (listOf(CodeBlock.of("b, s, lim")) + values).joinToCode(", "))
                .build(),
        )

        if (Generate.DATA in layout.generate) {
            val toData = bufferFunction("toData").returns(layout.dataClassName)
            if (layout.properties.isEmpty()) {
                toData.addStatement("return %T", layout.dataClassName)
            } else {
                toData.addStatement("return %T(%L)", layout.dataClassName, plan.fields.map { CodeBlock.of("%N = %L", it.name, dataValue(it)) }.joinToCode(", "))
            }
            builder.addFunction(toData.build())
        }

        // The bytes of a frame run from its start to its end, or from its end up to its start when mirrored.
        val range = { bytes: String, start: String, limit: CodeBlock ->
            val end = when {
                staticSize == null -> CodeBlock.of("end($bytes, $start, %L)", limit)
                plan.mirrored -> CodeBlock.of("$start - %L", staticSize)
                else -> CodeBlock.of("$start + %L", staticSize)
            }
            if (plan.mirrored) CodeBlock.of("%L, $start", end) else CodeBlock.of("$start, %L", end)
        }
        val own = range("b", "s", CodeBlock.of("lim"))
        val contentEquals = bufferFunction("contentEquals").addParameter("other", ANY.copy(nullable = true)).returns(BOOLEAN)
        val comparison = CodeBlock.builder().beginControlFlow("when (other)")
        if (context.index == 0) {
            val viewArguments = rootArguments(plan, "other.bytes")
            comparison.addStatement(
                "is %T -> %T.rangeEquals(b, %L, other.bytes, %L)",
                layout.viewClassName,
                VIEW_BYTES,
                own,
                range("other.bytes", viewArguments.start, viewArguments.limit),
            )
        }
        comparison.addStatement(
            "is %T -> %T.rangeEquals(b, %L, other.$SLICE_BYTES, %L)",
            context.sliceName,
            VIEW_BYTES,
            own,
            range("other.$SLICE_BYTES", "other.$SLICE_START", CodeBlock.of("other.$SLICE_LIMIT")),
        )
        comparison.addStatement("else -> false").endControlFlow()
        if (staticSize != null) {
            contentEquals.addCode("return %L", comparison.build())
        } else {
            // A view over bytes too short for its flag header has no end to compare up to.
            contentEquals.beginControlFlow("return try").addCode(comparison.build()).nextControlFlow("catch (e: %T)", RUNTIME_EXCEPTION).addStatement("false").endControlFlow()
        }
        builder.addFunction(contentEquals.build())
        val hash = bufferFunction("contentHashCode").returns(INT)
        if (staticSize != null) {
            hash.addStatement("return %T.rangeHashCode(b, %L)", VIEW_BYTES, own)
        } else {
            hash.beginControlFlow("return try").addStatement("%T.rangeHashCode(b, %L)", VIEW_BYTES, own)
                .nextControlFlow("catch (e: %T)", RUNTIME_EXCEPTION).addStatement("0").endControlFlow()
        }
        builder.addFunction(hash.build())

        val description = CodeBlock.builder().add("name + %S", "(")
        plan.fields.forEachIndexed { index, field ->
            description.add(" + %S + get${field.name.capitalized()}(b, s, lim)", (if (index == 0) "" else ", ") + field.name + "=")
        }
        description.add(" + %S", ")")
        builder.addFunction(
            bufferFunction("describe", "name")
                .returns(STRING)
                .beginControlFlow("return try")
                .addStatement("%L", description.build())
                .nextControlFlow("catch (e: %T)", RUNTIME_EXCEPTION)
                .addStatement(
                    "name + %S + %T.hex(b, %L) + %S",
                    "(",
                    VIEW_BYTES,
                    when {
                        plan.mirrored && staticSize != null -> CodeBlock.of("s - SIZE, s")
                        plan.mirrored -> CodeBlock.of("lim - %L, s", plan.footer)
                        staticSize != null -> CodeBlock.of("s, s + SIZE")
                        else -> CodeBlock.of("s, lim + %L", plan.footer)
                    },
                    ")",
                )
                .endControlFlow()
                .build(),
        )
        return builder.build()
    }

    /** Positions relative to the frame start `s`, following the decoder. */
    private inner class FrameCode(private val plan: ViewPlan) {

        val mirrored: Boolean get() = plan.mirrored

        fun anchor(anchor: Anchor): CodeBlock = when (anchor) {
            is Anchor.End -> CodeBlock.of("endOf%L(b, s, lim)", anchor.name.capitalized())
            is Anchor.Aligned -> CodeBlock.of("%T.alignBits(%L)", VIEW_BYTES, bits(Cursor(anchor.inner, anchor.bits)))
        }

        /** The bit offset of [cursor] from `s`. */
        fun bits(cursor: Cursor): CodeBlock = when {
            cursor.anchor == null -> CodeBlock.of("%L", cursor.bits)
            cursor.bits == 0 -> anchor(cursor.anchor)
            else -> CodeBlock.of("%L + %L", anchor(cursor.anchor), cursor.bits)
        }

        /** The array index of the byte [cursor] rounds up to. */
        fun bytePos(cursor: Cursor): CodeBlock {
            val aligned = cursor.aligned()
            val sign = if (mirrored) "-" else "+"
            return when {
                aligned.anchor == null -> plan.offset(aligned.bits / Byte.SIZE_BITS)
                aligned.bits == 0 -> CodeBlock.of("s $sign %L / 8", anchor(aligned.anchor))
                else -> CodeBlock.of("s $sign %L / 8 $sign %L", anchor(aligned.anchor), aligned.bits / Byte.SIZE_BITS)
            }
        }

        fun presence(presence: Presence): CodeBlock = when (presence) {
            is Presence.Owned -> CodeBlock.of("%T.bit(b, s, %L, lim)", VIEW_BYTES, presence.bitPos)
            is Presence.AllSet -> presence.bitPositions.map { CodeBlock.of("%T.bit(b, s, %L, lim)", VIEW_BYTES, it) }.joinToCode(" && ")
        }

        fun location(field: FieldPlan): Location =
            if (field.access is Access.BodyBit) Location(CodeBlock.of("s"), bits(field.start)) else Location(bytePos(field.start), null, mirrored)
    }

    /**
     * Where a property's content is: the byte [pos], and for a body Boolean the [bit] counted from it. In a [mirrored]
     * frame [pos] is where the content ends, the content running downwards from it.
     */
    private class Location(val pos: CodeBlock, val bit: CodeBlock?, val mirrored: Boolean = false) {
        fun plus(bytes: Int): Location = if (bytes == 0) this else Location(CodeBlock.of(if (mirrored) "%L - %L" else "%L + %L", pos, bytes), bit, mirrored)

        /** Where [bytes] of content at this location start in the array. */
        fun start(bytes: Int): CodeBlock = if (mirrored) CodeBlock.of("%L - %L", pos, bytes) else pos
    }

    /** The frame start and body limit of a view over the whole of [bytes]: at its start, or at its end when mirrored. */
    private class Arguments(val start: String, val limit: CodeBlock)

    private fun rootArguments(plan: ViewPlan, bytes: String): Arguments = if (plan.mirrored) {
        Arguments("$bytes.size", CodeBlock.of("%L", plan.footer))
    } else {
        Arguments("0", CodeBlock.of(if (plan.footer == 0) "$bytes.size" else "$bytes.size - ${plan.footer}"))
    }

    /** The frame start and body limit of a view over `[from, to)`. */
    private fun rangeArguments(plan: ViewPlan): Arguments = if (plan.mirrored) {
        Arguments("to", if (plan.footer == 0) CodeBlock.of("from") else CodeBlock.of("from + %L", plan.footer))
    } else {
        Arguments("from", if (plan.footer == 0) CodeBlock.of("to") else CodeBlock.of("to - %L", plan.footer))
    }

    /** Logical offset [offset] of a frame at `s`: the byte it starts at, or in a mirrored frame the one it ends at. */
    private fun ViewPlan.offset(offset: Int): CodeBlock = when {
        !mirrored -> at(offset)
        offset == 0 -> CodeBlock.of("s")
        else -> CodeBlock.of("s - %L", offset)
    }

    /**
     * Walks the properties the way the encoder writes them, from their values rather than from the flag header, into
     * `bitCursor`: a property is written when it is not `null`, whatever its presence bits say. Positions are
     * constant-folded up to the first property whose size depends on its value.
     */
    private inner class Walk(private val function: FunSpec.Builder, start: Int, val dry: Boolean, val mirrored: Boolean = false) {
        private var constant = start
        private var runtime = false

        fun goRuntime() {
            if (!runtime) {
                function.addStatement("var $BIT_CURSOR = %L", constant)
                runtime = true
            }
        }

        fun advance(bits: Int) {
            if (bits == 0) return
            if (runtime) function.addStatement("$BIT_CURSOR += %L", bits) else constant += bits
        }

        fun advanceBytes(bytes: CodeBlock) {
            goRuntime()
            function.addStatement("$BIT_CURSOR += %L * 8", bytes)
        }

        fun align() {
            if (runtime) function.addStatement("$BIT_CURSOR = %T.alignBits($BIT_CURSOR)", VIEW_BYTES) else constant = alignBits(constant)
        }

        val bytePos: CodeBlock get() = when {
            !runtime -> if (mirrored) (if (constant == 0) CodeBlock.of("s") else CodeBlock.of("s - %L", constant / Byte.SIZE_BITS)) else at(constant / Byte.SIZE_BITS)
            mirrored -> CodeBlock.of("s - $BIT_CURSOR / 8")
            else -> CodeBlock.of("s + $BIT_CURSOR / 8")
        }

        val location: Location get() = Location(bytePos, null, mirrored)
        val bitPos: CodeBlock get() = if (runtime) CodeBlock.of(BIT_CURSOR) else CodeBlock.of("%L", constant)

        fun endPos(): CodeBlock = when {
            !runtime && mirrored -> alignBits(constant).let { if (it == 0) CodeBlock.of("s") else CodeBlock.of("s - %L", it / Byte.SIZE_BITS) }
            !runtime -> at(alignBits(constant) / Byte.SIZE_BITS)
            mirrored -> CodeBlock.of("s - %T.alignBits($BIT_CURSOR) / 8", VIEW_BYTES)
            else -> CodeBlock.of("s + %T.alignBits($BIT_CURSOR) / 8", VIEW_BYTES)
        }

        fun endBytes(footer: Int): CodeBlock = if (runtime) {
            if (footer == 0) CodeBlock.of("%T.alignBits($BIT_CURSOR) / 8", VIEW_BYTES) else CodeBlock.of("%T.alignBits($BIT_CURSOR) / 8 + %L", VIEW_BYTES, footer)
        } else {
            CodeBlock.of("%L", alignBits(constant) / Byte.SIZE_BITS + footer)
        }

        fun statement(format: String, vararg args: Any) {
            if (!dry) function.addStatement(format, *args)
        }

        fun code(code: CodeBlock) = function.addStatement("%L", code)

        fun begin(format: String, vararg args: Any) = function.beginControlFlow(format, *args)

        fun end() = function.endControlFlow()
    }

    private fun walk(walk: Walk, plan: ViewPlan, names: Map<FieldPlan, String>) {
        plan.fields.forEach { field ->
            if (field.field.reservedBefore > 0) {
                walk.align()
                walk.advance(field.field.reservedBefore * Byte.SIZE_BITS)
            }
            val value = CodeBlock.of("%N", names.getValue(field))
            val access = field.access
            if (access is Access.Collection) {
                walkCollection(walk, field, access, value)
            } else if (field.nullable) {
                val hasBody = field.access !is Access.HeaderBit && field.access !is Access.PackedEnum && field.access !is Access.PackedNumber
                if (hasBody || !walk.dry) {
                    if (hasBody) walk.goRuntime()
                    walk.begin("if (%L != null)", value)
                    (field.presence as? Presence.Owned)?.let { walk.statement("%T.setBit(b, s, %L, true, lim)", VIEW_BYTES, it.bitPos) }
                    walkContent(walk, field, value)
                    walk.end()
                }
            } else {
                walkContent(walk, field, value)
            }
            if (field.field.reservedAfter > 0) {
                walk.align()
                walk.advance(field.field.reservedAfter * Byte.SIZE_BITS)
            }
        }
    }

    private fun walkContent(walk: Walk, field: FieldPlan, value: CodeBlock) {
        val leaf = unwrap(field.value, value)
        when (val access = field.access) {
            is Access.Collection -> error("Walked by walkCollection")

            is Access.HeaderBit, is Access.PackedNumber, is Access.PackedEnum -> if (!walk.dry) {
                write(field, access, Location(CodeBlock.of("s"), null), leaf).forEach { walk.code(it) }
            }

            is Access.BodyBit -> {
                if (!walk.dry) write(field, access, Location(CodeBlock.of("s"), walk.bitPos), leaf).forEach { walk.code(it) }
                walk.advance(1)
            }

            is Access.Nested -> {
                val plan = access.context.plan!!.getOrThrow()
                val size = plan.staticSize
                val contents = contentsArgument(plan.hasStuffed())
                walk.align()
                when {
                    size != null -> {
                        walk.statement("%T.write(b, %L, %L + %L, %L)", access.context.layoutName, walk.bytePos, walk.bytePos, size - plan.footer, value)
                        walk.advance(size * Byte.SIZE_BITS)
                    }

                    walk.dry -> walk.advanceBytes(CodeBlock.of("%T.sizeOf(%L$contents)", access.context.layoutName, value))

                    else -> {
                        walk.goRuntime()
                        walk.code(CodeBlock.of("$BIT_CURSOR = (%T.write(b, %L, lim, %L$contents) - s) * 8", access.context.layoutName, walk.bytePos, value))
                    }
                }
            }

            is Access.Number -> when (val width = access.width) {
                is Width.Fixed -> {
                    walk.align()
                    if (!walk.dry) write(field, access, walk.location, leaf).forEach { walk.code(it) }
                    walk.advance(width.length.bytes * Byte.SIZE_BITS)
                }

                is Width.Selected -> walkSelected(walk, field, access, width, leaf)
            }

            is Access.Text -> {
                walk.align()
                if (!walk.dry) write(field, access, walk.location, leaf).forEach { walk.code(it) }
                val fixed = access.fixedBytes
                if (fixed !=
                    null
                ) {
                    walk.advance(fixed * Byte.SIZE_BITS)
                } else {
                    walk.advanceBytes(CodeBlock.of("%T.sizeOf(%L, %N)", VIEW_STRINGS, leaf, "${field.name}String"))
                }
            }

            is Access.EnumTable -> {
                walk.align()
                if (!walk.dry) write(field, access, walk.location, leaf).forEach { walk.code(it) }
                val fixed = access.fixedBytes
                if (fixed != null) {
                    walk.advance(fixed * Byte.SIZE_BITS)
                } else {
                    walk.advanceBytes(CodeBlock.of("(%L + %N[%L.ordinal].size)", (access.prefix?.size ?: 0) + (access.postfix?.size ?: 0), "${field.name}Table", leaf))
                }
            }

            is Access.Sealed -> {
                val contents = contentsArgument(access.context.sealedPlan!!.getOrThrow().hasStuffed())
                walk.align()
                if (walk.dry) {
                    walk.advanceBytes(CodeBlock.of("%T.sizeOf(%L$contents)", access.context.layoutName, value))
                } else {
                    walk.goRuntime()
                    walk.code(CodeBlock.of("$BIT_CURSOR = (%T.writeValues(b, %L, lim, %L$contents) - s) * 8", access.context.layoutName, walk.bytePos, value))
                }
            }

            is Access.Character, is Access.Framed -> {
                walk.align()
                if (!walk.dry) write(field, access, walk.location, leaf).forEach { walk.code(it) }
                walk.advance(fixedContentBytes(access) * Byte.SIZE_BITS)
            }
        }
    }

    private fun walkSelected(walk: Walk, field: FieldPlan, access: Access.Number, width: Width.Selected, value: CodeBlock) {
        walk.goRuntime()
        val name = field.name.capitalized()
        val kind = field.value.leafKind
        val settings = access.settings
        val length = "lengthOf$name"
        val number = encoderNumber(kind, value, (settings as? NumericSettings.Natural)?.signed == false || (settings as? NumericSettings.Scalar)?.signed == false)
        when (settings) {
            is NumericSettings.Decimal -> walk.code(CodeBlock.of("val $length = %T.decimalLength(%L)", NUMERIC_CODEC, value))

            is NumericSettings.MedFloat -> walk.code(CodeBlock.of("val $length = %T.medFloatLength(%L.toDouble())", NUMERIC_CODEC, value))

            is NumericSettings.Scalar -> {
                walk.code(CodeBlock.of("val wireOf$name = %T.scalarToWire(%N, %L)", NUMERIC_CODEC, "${field.name}Settings", number))
                walk.code(CodeBlock.of("val indexOf$name = %T.selectLengthIndex(%N, wireOf$name, %L)", NUMERIC_CODEC, "${field.name}Lengths", settings.signed))
                walk.code(CodeBlock.of("val $length = %N[indexOf$name]", "${field.name}Lengths"))
            }

            is NumericSettings.Natural -> {
                walk.code(
                    CodeBlock.of(
                        "val indexOf$name = %T.selectLengthIndex(%N, %L, %L)",
                        NUMERIC_CODEC,
                        "${field.name}Lengths",
                        toLong(kind, value, !settings.signed),
                        settings.signed,
                    ),
                )
                walk.code(CodeBlock.of("val $length = %N[indexOf$name]", "${field.name}Lengths"))
            }

            is NumericSettings.RangeEncoded -> error("A range has a single size")
        }
        when (width.kind) {
            Width.Selected.Kind.INDEX -> walk.statement("%T.setBits(b, s, %L, %L, indexOf$name.toLong(), lim)", VIEW_BYTES, width.bitPos, width.bits)
            Width.Selected.Kind.LARGER -> walk.statement("%T.setBit(b, s, %L, $length == %L, lim)", VIEW_BYTES, width.bitPos, length(width.lengths.last()))
        }
        walk.align()
        if (!walk.dry) {
            val pos = walk.bytePos
            val order = order(access.writeOrder)
            val statement = when (settings) {
                is NumericSettings.Natural -> CodeBlock.of(
                    "%T.writeNatural(b, %L, %L, $length, %L, %L, lim)",
                    VIEW_BYTES,
                    pos,
                    toLong(kind, value, !settings.signed),
                    settings.signed,
                    order,
                )

                is NumericSettings.Scalar -> CodeBlock.of("%T.writeNatural(b, %L, wireOf$name, $length, %L, %L, lim)", VIEW_BYTES, pos, settings.signed, order)

                is NumericSettings.Decimal -> CodeBlock.of(
                    "if ($length == %L) %T.writeDouble(b, %L, %L.toDouble(), %L, lim) else %T.writeFloat(b, %L, %L.toFloat(), %L, lim)",
                    length(Length.`64_BIT`), VIEW_BYTES, pos, value, order(access.writeOrder), VIEW_BYTES, pos, value, order(access.writeOrder),
                )

                is NumericSettings.MedFloat -> CodeBlock.of(
                    "if ($length == %L) %T.writeMedFloat32(b, %L, %L.toDouble(), lim) else %T.writeMedFloat16(b, %L, %L.toDouble(), lim)",
                    length(Length.`32_BIT`),
                    VIEW_BYTES,
                    pos,
                    value,
                    VIEW_BYTES,
                    pos,
                    value,
                )

                is NumericSettings.RangeEncoded -> error("A range has a single size")
            }
            walk.code(statement)
        }
        walk.advanceBytes(CodeBlock.of("$length.bytes"))
    }

    private fun Access.takesParent(): Boolean = this is Access.Nested || this is Access.Sealed || this is Access.Collection

    private fun checksumConstant(name: String, spec: ChecksumSpec) = PropertySpec.builder(name, CHECKSUM_SPEC, KModifier.PRIVATE)
        .initializer(
            "%T(%L, 0x%LuL, 0x%LuL, 0x%LuL, %L, %L)",
            CHECKSUM_SPEC,
            spec.width,
            spec.polynomial.toString(16),
            spec.init.toString(16),
            spec.xorOut.toString(16),
            spec.reflectIn,
            spec.reflectOut,
        )
        .build()

    /** Whether a frame holds a stuffed collection, whose content sizing builds once for the write that follows. */
    private fun ViewPlan.hasStuffed(): Boolean = fields.any { it.access.hasStuffed() }

    private fun SealedPlan.hasStuffed(): Boolean = leaves.any { it.context.plan!!.getOrThrow().hasStuffed() }

    private fun Access.hasStuffed(): Boolean = when (this) {
        is Access.Nested -> context.plan!!.getOrThrow().hasStuffed()
        is Access.Sealed -> context.sealedPlan!!.getOrThrow().hasStuffed()
        is Access.Collection -> count is Count.Stuffed || items.any { it.plan.hasStuffed() }
        else -> false
    }

    private fun contentsParameter(): ParameterSpec = ParameterSpec.builder(CONTENTS, VIEW_CONTENTS.copy(nullable = true)).defaultValue("null").build()

    private fun contentsArgument(stuffed: Boolean): String = if (stuffed) ", $CONTENTS" else ""

    private fun ViewPlan.hasChecksums(): Boolean = checksum != null || fields.any { it.access.hasChecksums() }

    private fun SealedPlan.hasChecksums(): Boolean = checksum != null || leaves.any { it.context.plan!!.getOrThrow().hasChecksums() }

    private fun Access.hasChecksums(): Boolean = when (this) {
        is Access.Nested -> context.plan!!.getOrThrow().hasChecksums()

        is Access.Sealed -> context.sealedPlan!!.getOrThrow().hasChecksums()

        // Items of a stuffed collection are read from a copy, so there is nothing to update in place.
        is Access.Collection -> count !is Count.Stuffed && items.any { it.plan.hasChecksums() }

        is Access.Framed -> checksum != null

        else -> false
    }

    /** Statements for one property that only run when it is present, with its position in `pos`. */
    private fun FunSpec.Builder.forPresent(field: FieldPlan, frame: FrameCode, block: FunSpec.Builder.() -> Unit) {
        val presence = field.presence?.let { frame.presence(it) }
        val empty = (field.access as? Access.Collection)?.emptyBit?.let { CodeBlock.of("%T.bit(b, s, %L, lim)", VIEW_BYTES, it) }
        val condition = listOfNotNull(presence, empty).takeIf { it.isNotEmpty() }?.joinToCode(" && ")
        if (condition != null) beginControlFlow("if (%L)", condition) else beginControlFlow("run")
        addStatement("val pos = %L", frame.location(field).pos)
        block()
        endControlFlow()
    }

    /** Visits every item of [access]; [visit] reads the item frame at `item` from the array and limit it is given. */
    private fun FunSpec.Builder.forEachItem(field: FieldPlan, access: Access.Collection, mirrored: Boolean, visit: (ItemFrame, String, String) -> CodeBlock) {
        collectionCount(field, access, mirrored)
        val (bytes, limit) = itemSource(access)
        beginControlFlow(
            "%T.forEach($bytes, first, $limit, count, %L, %L, %L, %L) { frame, item ->",
            VIEW_COLLECTIONS,
            terminator(access),
            access.items[0].reference(),
            access.items.getOrNull(1)?.reference() ?: CodeBlock.of("null"),
            mirrored,
        )
        if (access.items.size == 1) {
            addStatement("%L", visit(access.items.single(), bytes, limit))
        } else {
            beginControlFlow("when (frame)")
            access.items.forEachIndexed { index, item -> addStatement("%L -> %L", index, visit(item, bytes, limit)) }
            addStatement("else -> Unit")
            endControlFlow()
        }
        endControlFlow()
    }

    /** Recomputes every checksum in the frame at `s`, those of nested frames first. */
    private fun updateChecksums(plan: ViewPlan, frame: FrameCode): FunSpec {
        val function = bufferFunction("updateChecksums")
        plan.fields.filter { it.access.hasChecksums() }.forEach { field ->
            function.forPresent(field, frame) {
                when (val access = field.access) {
                    is Access.Nested -> addStatement("%T.updateChecksums(b, pos, %L)", access.context.layoutName, nestedLimit(access, CodeBlock.of("pos")))

                    is Access.Sealed -> addStatement("%T.updateChecksums(b, pos, %L)", access.context.layoutName, sealedLimit(access))

                    is Access.Collection -> forEachItem(field, access, plan.mirrored) { item, bytes, limit ->
                        if (item.plan.hasChecksums()) CodeBlock.of("%T.updateChecksums($bytes, item, $limit)", item.objectName) else CodeBlock.of("Unit")
                    }

                    is Access.Framed -> {
                        val prefix = access.prefix?.size ?: 0
                        addStatement(
                            "%T.update(b, pos + %L, pos + %L, %N, %L, lim)",
                            VIEW_CHECKSUM,
                            prefix,
                            prefix + fixedContentBytes(access.inner),
                            "${field.name}Checksum",
                            order(access.checksumOrder),
                        )
                    }

                    else -> Unit
                }
            }
        }
        if (plan.checksum != null) {
            function.addStatement("val end = %L", FrameCode(plan).bytePos(plan.bodyEnd))
            function.addStatement("%L", frameChecksum(plan, CodeBlock.of("end"), "update")!!)
        }
        return function.build()
    }

    /**
     * Checks the frame at `s` the way the decoder reads it: its prefix, every property (reading it, and checking the
     * frames of nested layouts, items and value classes), its checksum when `checkChecksum`, and its postfix.
     */
    private fun validate(plan: ViewPlan, frame: FrameCode): FunSpec {
        val function = bufferFunction("validate").addParameter("checkChecksum", BOOLEAN)
        plan.prefix?.let {
            if (plan.mirrored) {
                function.addStatement("%T.checkPrefix(b, s - %L, %N, b.size)", VIEW_CHECKSUM, it.size, FRAME_PREFIX)
            } else {
                function.addStatement("%T.checkPrefix(b, s, %N, lim + %L)", VIEW_CHECKSUM, FRAME_PREFIX, plan.footer)
            }
        }
        plan.fields.forEach { field ->
            val get = CodeBlock.of("get${field.name.capitalized()}(b, s, lim)")
            function.forPresent(field, frame) {
                when (val access = field.access) {
                    is Access.Nested -> addStatement("%T.validate(b, pos, %L, checkChecksum)", access.context.layoutName, nestedLimit(access, CodeBlock.of("pos")))

                    is Access.Sealed -> addStatement("%T.validate(b, pos, %L, checkChecksum)", access.context.layoutName, sealedLimit(access))

                    is Access.Collection -> forEachItem(field, access, plan.mirrored) { item, bytes, limit ->
                        CodeBlock.of("%T.validate($bytes, item, $limit, checkChecksum)", item.objectName)
                    }

                    is Access.Framed -> {
                        val prefix = access.prefix?.size ?: 0
                        val innerEnd = prefix + fixedContentBytes(access.inner)
                        access.prefix?.let { addStatement("%T.checkPrefix(b, pos, %N, lim)", VIEW_CHECKSUM, "${field.name}FramePrefix") }
                        addStatement("%L", get)
                        access.checksum?.let {
                            beginControlFlow("if (checkChecksum)")
                            addStatement("%T.check(b, pos + %L, pos + %L, %N, %L, lim)", VIEW_CHECKSUM, prefix, innerEnd, "${field.name}Checksum", order(access.checksumOrder))
                            nextControlFlow("else")
                            addStatement("%T.checkRange(pos + %L, %L, lim)", VIEW_BYTES, innerEnd, it.crc.byteWidth)
                            endControlFlow()
                        }
                        access.postfix?.let {
                            addStatement("%T.checkPostfix(b, pos + %L, %N, lim)", VIEW_CHECKSUM, innerEnd + (access.checksum?.crc?.byteWidth ?: 0), "${field.name}FramePostfix")
                        }
                    }

                    is Access.EnumTable -> if (plan.mirrored) {
                        val prefix = access.prefix?.size ?: 0
                        val size = access.table.first().size
                        access.prefix?.let { addStatement("%T.checkPrefix(b, pos - %L, %N, b.size)", VIEW_CHECKSUM, prefix, "${field.name}Prefix") }
                        addStatement("%T.matchIndex(b, pos - %L, %N, b.size)", VIEW_BYTES, prefix + size, "${field.name}Table")
                        access.postfix?.let { addStatement("%T.checkPostfix(b, pos - %L, %N, b.size)", VIEW_CHECKSUM, prefix + size + it.size, "${field.name}Postfix") }
                    } else {
                        val prefix = access.prefix?.size ?: 0
                        access.prefix?.let { addStatement("%T.checkPrefix(b, pos, %N, lim)", VIEW_CHECKSUM, "${field.name}Prefix") }
                        addStatement("val index = %T.matchIndex(b, pos + %L, %N, lim)", VIEW_BYTES, prefix, "${field.name}Table")
                        access.postfix?.let {
                            addStatement("%T.checkPostfix(b, pos + %L + %N[index].size, %N, lim)", VIEW_CHECKSUM, prefix, "${field.name}Table", "${field.name}Postfix")
                        }
                    }

                    // Checked without decoding it into a String.
                    is Access.Text -> if (plan.mirrored) addStatement("%L", get) else addStatement("%T.check(b, pos, lim, %N)", VIEW_STRINGS, "${field.name}String")

                    else -> addStatement("%L", get)
                }
            }
        }
        function.addStatement("val end = %L", frame.bytePos(plan.bodyEnd))
        val crc = plan.checksum?.crc?.byteWidth ?: 0
        if (plan.mirrored) {
            function.addStatement("%T.checkRange(end - %L, %L, b.size)", VIEW_BYTES, plan.footer, plan.footer)
            frameChecksum(plan, CodeBlock.of("end"), "check")?.let { function.addStatement("if (checkChecksum) %L", it) }
            plan.postfix?.let { function.addStatement("%T.checkPostfix(b, end - %L, %N, b.size)", VIEW_CHECKSUM, crc + it.size, FRAME_POSTFIX) }
        } else {
            function.addStatement("%T.checkRange(end, %L, lim + %L)", VIEW_BYTES, plan.footer, plan.footer)
            frameChecksum(plan, CodeBlock.of("end"), "check")?.let { function.addStatement("if (checkChecksum) %L", it) }
            plan.postfix?.let { function.addStatement("%T.checkPostfix(b, end + %L, %N, lim + %L)", VIEW_CHECKSUM, crc, FRAME_POSTFIX, plan.footer) }
        }
        return function.build()
    }

    /**
     * The call that updates or checks the checksum of a frame whose body ends at [bodyEnd]. The body runs from the end
     * of the prefix; in a mirrored frame it lies below the prefix and the checksum below the body.
     */
    private fun frameChecksum(plan: ViewPlan, bodyEnd: CodeBlock, function: String): CodeBlock? {
        val checksum = plan.checksum ?: return null
        val prefix = plan.prefix?.size ?: 0
        return if (plan.mirrored) {
            CodeBlock.of(
                "%T.%N(b, %L, %L, %N, %L, b.size, %L - %L)",
                VIEW_CHECKSUM,
                function,
                bodyEnd,
                plan.offset(prefix),
                FRAME_CHECKSUM,
                order(plan.checksumOrder),
                bodyEnd,
                checksum.crc.byteWidth,
            )
        } else {
            CodeBlock.of("%T.%N(b, %L, %L, %N, %L, lim + %L)", VIEW_CHECKSUM, function, at(prefix), bodyEnd, FRAME_CHECKSUM, order(plan.checksumOrder), plan.footer)
        }
    }

    /** The limit a sealed frame nested at a varying position reads up to: its parent's, minus its postfix. */
    private fun sealedLimit(access: Access.Sealed): CodeBlock {
        val footer = access.context.sealedPlan!!.getOrThrow().footer
        return if (footer == 0) CodeBlock.of("lim") else CodeBlock.of("lim - %L", footer)
    }

    private fun generateSealed(layout: Layout): FileSpec {
        val root = planner.root(layout)!!
        val plan = root.sealedPlan!!.getOrThrow()
        return FileSpec.builder(layout.frameClassName)
            .indent("    ")
            .addFileComment("Generated by the Kaluga bytes KSP processor from %L. Do not edit.", layout.qualifiedName)
            .addAnnotation(OPT_IN_INTERNAL)
            .addType(frameType(layout, root, plan))
            .apply { planner.plannedContexts(layout).forEach { addType(sealedObject(it, it.sealedPlan!!.getOrThrow())) } }
            .build()
    }

    private fun frameType(layout: Layout, root: ViewContext, plan: SealedPlan): TypeSpec {
        val frame = layout.frameClassName
        val lim = CodeBlock.of(if (plan.footer == 0) "bytes.size" else "bytes.size - ${plan.footer}")
        val builder = TypeSpec.classBuilder(frame)
            .addModifiers(KModifier.VALUE)
            .addAnnotation(JVM_INLINE)
            .addKdoc(
                "The zero-copy frame of the sealed [%T] over [bytes]: its [value] is a view of the subtype the bytes hold.\n\n" +
                    "It does not implement [%T], whose subtypes the sealed hierarchy lists itself. `==` compares the backing arrays by reference; " +
                    "use [contentEquals] to compare content.",
                layout.interfaceClassName,
                layout.interfaceClassName,
            )
            .primaryConstructor(FunSpec.constructorBuilder().addParameter("bytes", BYTE_ARRAY).build())
            .addProperty(PropertySpec.builder("bytes", BYTE_ARRAY).initializer("bytes").build())
            .addProperty(
                PropertySpec.builder("value", layout.interfaceClassName)
                    .addKdoc("A view of the subtype these bytes hold, read in place.")
                    .getter(
                        FunSpec.getterBuilder()
                            .apply {
                                if (plan.hasChecksums()) {
                                    addStatement(
                                        "return %T.getValue(bytes, 0, %L, %T { %T.updateChecksums(bytes, 0, %L) })",
                                        root.layoutName,
                                        lim,
                                        VIEW_PARENT,
                                        root.layoutName,
                                        lim,
                                    )
                                } else {
                                    addStatement("return %T.getValue(bytes, 0, %L)", root.layoutName, lim)
                                }
                            }
                            .build(),
                    )
                    .build(),
            )
            .addFunction(
                FunSpec.builder("validate")
                    .addKdoc("Checks these bytes the way `BytesFormat` decodes them, throwing its exception for the first problem found.")
                    .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                    .addStatement("%T.validate(bytes, 0, %L, validateChecksum)", root.layoutName, lim)
                    .build(),
            )
        if (plan.hasChecksums()) {
            builder.addFunction(
                FunSpec.builder("isChecksumValid")
                    .addKdoc("Whether every checksum in these bytes matches; like [validate], it throws for anything else wrong.")
                    .returns(BOOLEAN)
                    .beginControlFlow("return try")
                    .addStatement("%T.validate(bytes, 0, %L, true)", root.layoutName, lim)
                    .addStatement("true")
                    .nextControlFlow("catch (e: %T)", INVALID_CHECKSUM)
                    .addStatement("false")
                    .endControlFlow()
                    .build(),
            )
        }
        if (layout.isInternal) builder.addModifiers(KModifier.INTERNAL)
        if (Generate.DATA in layout.generate) {
            builder.addFunction(FunSpec.builder("toData").returns(layout.dataClassName).addStatement("return %T.toData(value)", root.layoutName).build())
        }
        builder.addFunction(
            FunSpec.builder("contentEquals").addParameter("other", frame).returns(BOOLEAN)
                .addStatement(
                    "return %T.rangeEquals(bytes, 0, %T.end(bytes, 0, %L), other.bytes, 0, %T.end(other.bytes, 0, other.%L))",
                    VIEW_BYTES,
                    root.layoutName,
                    lim,
                    root.layoutName,
                    lim,
                )
                .build(),
        )
        builder.addFunction(
            FunSpec.builder("toString").addModifiers(KModifier.OVERRIDE).returns(STRING).addStatement("return %S + value + %S", frame.simpleName + "(", ")").build(),
        )
        val companion = TypeSpec.companionObjectBuilder()
            .addFunction(
                FunSpec.builder("encode")
                    .addKdoc("Encodes [value] into a new [%T].", frame)
                    .addParameter("value", layout.interfaceClassName)
                    .returns(frame)
                    .apply { if (plan.hasStuffed()) addStatement("val $CONTENTS = %T()", VIEW_CONTENTS) }
                    .addStatement("val size = %T.sizeOf(value${contentsArgument(plan.hasStuffed())})", root.layoutName)
                    .addStatement(
                        "return %T(%T(size).also { %T.writeValues(it, 0, %L, value${contentsArgument(plan.hasStuffed())}) })",
                        frame,
                        BYTE_ARRAY,
                        root.layoutName,
                        if (plan.footer ==
                            0
                        ) {
                            CodeBlock.of("size")
                        } else {
                            CodeBlock.of("size - %L", plan.footer)
                        },
                    )
                    .build(),
            )
            .addFunction(
                FunSpec.builder("wrap")
                    .addKdoc("A frame over [bytes], checked first as `BytesFormat` checks what it decodes; the constructor checks nothing.")
                    .addParameter("bytes", BYTE_ARRAY)
                    .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                    .returns(frame)
                    .addStatement("%T.validate(bytes, 0, %L, validateChecksum)", root.layoutName, lim)
                    .addStatement("return %T(bytes)", frame)
                    .build(),
            )
            .addFunction(
                FunSpec.builder("wrapRange")
                    .addKdoc(
                        "A view of the subtype of [%T] held in `[from, to)` of [bytes], checked first like [wrap], reading and writing it in place.",
                        layout.interfaceClassName,
                    )
                    .addParameter("bytes", BYTE_ARRAY)
                    .addParameter("from", INT)
                    .addParameter("to", INT)
                    .addParameter(ParameterSpec.builder("validateChecksum", BOOLEAN).defaultValue("true").build())
                    .returns(layout.interfaceClassName)
                    .addStatement("%T.checkWrapRange(bytes, from, to)", VIEW_BYTES)
                    .addStatement(
                        "%T.validate(bytes, from, %L, validateChecksum)",
                        root.layoutName,
                        if (plan.footer ==
                            0
                        ) {
                            CodeBlock.of("to")
                        } else {
                            CodeBlock.of("to - %L", plan.footer)
                        },
                    )
                    .addStatement("return %T.getValue(bytes, from, %L)", root.layoutName, if (plan.footer == 0) CodeBlock.of("to") else CodeBlock.of("to - %L", plan.footer))
                    .build(),
            )
        return builder.addType(companion.build()).build()
    }

    private fun sealedObject(context: ViewContext, plan: SealedPlan): TypeSpec {
        val layout = context.layout
        val builder = TypeSpec.objectBuilder(context.layoutName)
            .addModifiers(KModifier.INTERNAL)
            .addKdoc("The accessors of the sealed [%T] as compiled here, taking the array, the frame start and the end of the body.", layout.interfaceClassName)
        plan.prefix?.let { builder.addProperty(byteArrayConstant(FRAME_PREFIX, it)) }
        plan.postfix?.let { builder.addProperty(byteArrayConstant(FRAME_POSTFIX, it)) }
        plan.checksum?.let { builder.addProperty(checksumConstant(FRAME_CHECKSUM, it)) }
        val crcWidth = plan.checksum?.crc?.byteWidth ?: 0
        if (plan.sizeDispatch == null) {
            builder.addProperty(
                PropertySpec.builder("discriminators", ARRAY.parameterizedBy(BYTE_ARRAY), KModifier.PRIVATE)
                    .initializer("arrayOf(%L)", plan.leaves.map { it.discriminator!!.literal() }.joinToCode(", "))
                    .build(),
            )
        }
        val prefix = plan.prefix?.size ?: 0
        val start = at(prefix)

        fun leafStart(index: Int): CodeBlock =
            plan.leaves[index].discriminator?.takeIf { plan.sizeDispatch == null }?.let { CodeBlock.of("pos + %L", it.size) } ?: CodeBlock.of("pos")

        // The subtype at `pos`, as the decoder picks it: the first discriminator that matches, or the payload size.
        fun FunSpec.Builder.dispatch(branch: (Int) -> CodeBlock): FunSpec.Builder {
            addStatement("val pos = %L", start)
            if (plan.sizeDispatch == null) {
                beginControlFlow("return when (%T.matchIndex(b, pos, discriminators, lim))", VIEW_BYTES)
                plan.leaves.indices.forEach { addStatement("%L -> %L", it, branch(it)) }
                addStatement("else -> error(%S)", "No such discriminator")
            } else {
                addStatement("val remaining = lim - pos")
                beginControlFlow("return when (remaining)")
                plan.sizeDispatch.forEach { (size, index) -> addStatement("%L -> %L", size, branch(index)) }
                if (plan.fallback != null) {
                    addStatement("else -> %L", branch(plan.fallback))
                } else {
                    addStatement(
                        "else -> throw %T(%P)",
                        SERIALIZATION_EXCEPTION,
                        CodeBlock.of("No @SizePolymorphic subtype registered for size \$remaining in ${plan.serialName}. Expected one of ${plan.sizeDispatch.keys}."),
                    )
                }
            }
            endControlFlow()
            return this
        }

        fun leafLimit(index: Int, pos: CodeBlock): CodeBlock = nestedLimit(Access.Nested(plan.leaves[index].context), pos)

        builder.addFunction(
            bufferFunction("getValue").returns(layout.interfaceClassName)
                .addParameter(ParameterSpec.builder(PARENT, VIEW_PARENT.copy(nullable = true)).defaultValue("null").build())
                .dispatch { CodeBlock.of("%T(b, %L, %L, $PARENT)", plan.leaves[it].context.sliceName, leafStart(it), leafLimit(it, leafStart(it))) }
                .build(),
        )
        fun leafEnd(index: Int): CodeBlock = CodeBlock.of("%T.end(b, %L, %L)", plan.leaves[index].context.layoutName, leafStart(index), leafLimit(index, leafStart(index)))
        builder.addFunction(
            bufferFunction("validate").addParameter("checkChecksum", BOOLEAN)
                .apply { plan.prefix?.let { addStatement("%T.checkPrefix(b, s, %N, lim + %L)", VIEW_CHECKSUM, FRAME_PREFIX, plan.footer) } }
                .addStatement("val end = subtypeEnd(b, s, lim, checkChecksum)")
                .addStatement("%T.checkRange(end, %L, lim + %L)", VIEW_BYTES, plan.footer, plan.footer)
                .apply {
                    plan.checksum?.let {
                        addStatement("if (checkChecksum) %T.check(b, %L, end, %N, %L, lim + %L)", VIEW_CHECKSUM, start, FRAME_CHECKSUM, order(plan.checksumOrder), plan.footer)
                    }
                    plan.postfix?.let { addStatement("%T.checkPostfix(b, end + %L, %N, lim + %L)", VIEW_CHECKSUM, crcWidth, FRAME_POSTFIX, plan.footer) }
                }
                .build(),
        )
        // Validates the subtype and returns where it ends.
        builder.addFunction(
            bufferFunction("subtypeEnd").addModifiers(KModifier.PRIVATE).addParameter("checkChecksum", BOOLEAN).returns(INT)
                .dispatch { index ->
                    CodeBlock.of(
                        "%T.validate(b, %L, %L, checkChecksum).let { %L }",
                        plan.leaves[index].context.layoutName,
                        leafStart(index),
                        leafLimit(index, leafStart(index)),
                        leafEnd(index),
                    )
                }
                .build(),
        )
        if (plan.hasChecksums()) {
            builder.addFunction(
                bufferFunction("updateChecksums")
                    .addStatement("val end = updateSubtypeChecksums(b, s, lim)")
                    .apply {
                        plan.checksum?.let { addStatement("%T.update(b, %L, end, %N, %L, lim + %L)", VIEW_CHECKSUM, start, FRAME_CHECKSUM, order(plan.checksumOrder), plan.footer) }
                    }
                    .build(),
            )
            builder.addFunction(
                bufferFunction("updateSubtypeChecksums").addModifiers(KModifier.PRIVATE).returns(INT)
                    .dispatch { index ->
                        if (plan.leaves[index].context.plan!!.getOrThrow().hasChecksums()) {
                            CodeBlock.of(
                                "%T.updateChecksums(b, %L, %L).let { %L }",
                                plan.leaves[index].context.layoutName,
                                leafStart(index),
                                leafLimit(index, leafStart(index)),
                                leafEnd(index),
                            )
                        } else {
                            leafEnd(index)
                        }
                    }
                    .build(),
            )
        }
        builder.addFunction(
            bufferFunction("end").returns(INT)
                .dispatch { index ->
                    val leafEnd = CodeBlock.of("%T.end(b, %L, %L)", plan.leaves[index].context.layoutName, leafStart(index), leafLimit(index, leafStart(index)))
                    if (plan.footer == 0) leafEnd else CodeBlock.of("%L + %L", leafEnd, plan.footer)
                }
                .build(),
        )
        val stuffed = plan.hasStuffed()
        fun contents(leaf: SealedLeaf) = contentsArgument(leaf.context.plan!!.getOrThrow().hasStuffed())
        val sizeOf = FunSpec.builder("sizeOf").addParameter("value", layout.interfaceClassName).returns(INT)
        if (stuffed) sizeOf.addParameter(contentsParameter())
        sizeOf.beginControlFlow("return %L + when (value)", prefix + plan.footer)
        plan.leaves.forEach { leaf ->
            val discriminator = leaf.discriminator?.takeIf { plan.sizeDispatch == null }?.size ?: 0
            sizeOf.addStatement("is %T -> %L + %T.sizeOf(value${contents(leaf)})", leaf.layout.interfaceClassName, discriminator, leaf.context.layoutName)
        }
        sizeOf.addStatement("else -> throw %T(%P)", ILLEGAL_ARGUMENT_EXCEPTION, CodeBlock.of("\$value is not a subtype of ${plan.serialName} with a view"))
        sizeOf.endControlFlow()
        builder.addFunction(sizeOf.build())

        // Like a frame of a varying size, a sealed frame is only ever written into a new array.
        val write = bufferFunction("writeValues")
            .addKdoc("Writes the frame of [value] at [s], returning where it ends.")
            .addParameter("value", layout.interfaceClassName)
            .returns(INT)
        if (stuffed) write.addParameter(contentsParameter())
        if (plan.prefix != null) write.addStatement("%T.write(b, s, %N, lim)", VIEW_BYTES, FRAME_PREFIX)
        write.addStatement("val pos = %L", start)
        write.beginControlFlow("val $BODY_END = when (value)")
        plan.leaves.forEachIndexed { index, leaf ->
            write.beginControlFlow("is %T ->", leaf.layout.interfaceClassName)
            if (plan.sizeDispatch == null) write.addStatement("%T.write(b, pos, discriminators[%L], lim)", VIEW_BYTES, index)
            write.addStatement("%T.write(b, %L, lim, value${contents(leaf)})", leaf.context.layoutName, leafStart(index))
            write.endControlFlow()
        }
        write.addStatement("else -> throw %T(%P)", ILLEGAL_ARGUMENT_EXCEPTION, CodeBlock.of("\$value is not a subtype of ${plan.serialName} with a view"))
        write.endControlFlow()
        plan.checksum?.let {
            write.addStatement("%T.update(b, %L, $BODY_END, %N, %L, lim + %L)", VIEW_CHECKSUM, start, FRAME_CHECKSUM, order(plan.checksumOrder), plan.footer)
        }
        if (plan.postfix != null) write.addStatement("%T.write(b, $BODY_END + %L, %N, lim + %L)", VIEW_BYTES, crcWidth, FRAME_POSTFIX, plan.footer)
        write.addStatement(if (plan.footer == 0) "return $BODY_END" else "return $BODY_END + %L", plan.footer)
        builder.addFunction(write.build())

        if (Generate.DATA in layout.generate) {
            val toData = FunSpec.builder("toData").addParameter("value", layout.interfaceClassName).returns(layout.dataClassName)
            toData.beginControlFlow("return when (value)")
            plan.leaves.forEach { leaf -> toData.addStatement("is %T -> value.toData()", leaf.context.sliceName) }
            toData.addStatement("else -> %T.from(value)", layout.dataClassName)
            toData.endControlFlow()
            builder.addFunction(toData.build())
        }
        return builder.build()
    }

    private fun itemObject(frame: ItemFrame): TypeSpec {
        val type = frame.field.typeName()
        val name = frame.field.name.capitalized()
        val builder = TypeSpec.objectBuilder(frame.objectName)
            .addModifiers(KModifier.INTERNAL)
            .addKdoc("The accessors of one collection item frame: its prefix and flag header, then the item, padded to a byte.")
            .addSuperinterface(ITEM_END)
            .addSuperinterface(ITEM_READ.parameterizedBy(type))
            .addFunction(bufferFunction("read").addModifiers(KModifier.OVERRIDE).returns(type).addStatement("return get$name(b, s, lim)").build())
        if (frame.field.settable) {
            builder.addSuperinterface(ITEM_WRITE.parameterizedBy(type))
                .addFunction(bufferFunction("write").addModifiers(KModifier.OVERRIDE).addParameter("value", type).addStatement("set$name(b, s, lim, value)").build())
        }
        addFrameMembers(builder, frame.plan, item = true)
        return builder.build()
    }

    // An item object is its own ItemEnd, ItemRead and, when its item is settable, ItemWrite.
    private fun ItemFrame.reference(): CodeBlock = CodeBlock.of("%T", objectName)

    /** Statements that read the count of [access] at `pos` into `count` and the position of its first item into `first`. */
    private fun FunSpec.Builder.collectionCount(field: FieldPlan, access: Access.Collection, mirrored: Boolean = false) = apply {
        if (mirrored) {
            // Counts are prepended before the items, so the items start below them.
            when (val count = access.count) {
                is Count.Prefix -> {
                    addStatement("val count = %T.lengthPrefixCountDown(b, pos, lim, %L, %L)", VIEW_COLLECTIONS, endMarking(count.marking), order(count.order))
                    addStatement("val first = pos - %T.lengthPrefixSizeDown(b, pos, %L)", VIEW_COLLECTIONS, endMarking(count.marking))
                }

                is Count.Number -> {
                    val length = (count.width as Width.Fixed).length
                    addStatement("val count = %T.readNatural(b, pos - %L, %L, false, %L, b.size).toInt()", VIEW_BYTES, length.bytes, length(length), order(count.readOrder))
                    addStatement("val first = pos - %L", length.bytes)
                }

                else -> {
                    addStatement("val count = %T.UNBOUNDED", VIEW_COLLECTIONS)
                    addStatement("val first = pos")
                }
            }
            return@apply
        }
        when (val count = access.count) {
            is Count.Prefix -> {
                addStatement("val count = %T.lengthPrefixCount(b, pos, lim, %L, %L)", VIEW_COLLECTIONS, endMarking(count.marking), order(count.order))
                addStatement("val first = pos + %T.lengthPrefixSize(b, pos, lim, %L)", VIEW_COLLECTIONS, endMarking(count.marking))
            }

            is Count.Number -> {
                val length = when (val width = count.width) {
                    is Width.Fixed -> length(width.length)

                    is Width.Selected -> CodeBlock.of(
                        "%T.selectedLength(%N, %T.bits(b, s, %L, %L, lim).toInt())",
                        VIEW_BYTES,
                        "${field.name}CountLengths",
                        VIEW_BYTES,
                        width.bitPos,
                        width.bits,
                    )
                }
                addStatement("val countLength = %L", length)
                addStatement("val count = %T.readNatural(b, pos, countLength, false, %L, lim).toInt()", VIEW_BYTES, order(count.readOrder))
                addStatement("val first = pos + countLength.bytes")
            }

            is Count.Flag -> {
                addStatement("val count = %T.bits(b, s, %L, %L, lim).toInt()", VIEW_BYTES, count.bitPos, count.bits)
                addStatement("val first = pos")
            }

            is Count.Terminated, is Count.Unmarked -> {
                addStatement("val count = %T.UNBOUNDED", VIEW_COLLECTIONS)
                addStatement("val first = pos")
            }

            // The items are read from an unstuffed copy, up to its end.
            is Count.Stuffed -> {
                addStatement("val body = %T.unstuff(b, pos, lim, %N, %L)", VIEW_STUFFING, "${field.name}Stuffing", count.terminator.literal())
                addStatement("val count = %T.UNBOUNDED", VIEW_COLLECTIONS)
                addStatement("val first = 0")
            }
        }
    }

    /** The array and limit the items of [access] are read from, after [collectionCount]. */
    private fun itemSource(access: Access.Collection): Pair<String, String> = if (access.count is Count.Stuffed) "body" to "body.size" else "b" to "lim"

    private fun terminator(access: Access.Collection): CodeBlock = (access.count as? Count.Terminated)?.let { CodeBlock.of("%L", it.terminator.literal()) } ?: CodeBlock.of("null")

    private fun collectionGetter(getter: FunSpec.Builder, field: FieldPlan, access: Access.Collection, frame: FrameCode) {
        val value = field.value as ValueType.Collection
        field.presence?.let { getter.addStatement("if (!(%L)) return null", frame.presence(it)) }
        access.emptyBit?.let { getter.addStatement("if (!%T.bit(b, s, %L, lim)) return %L", VIEW_BYTES, it, emptyCollection(value)) }
        getter.addStatement("val pos = %L", frame.bytePos(field.start))
        getter.collectionCount(field, access, frame.mirrored)
        val terminator = terminator(access)
        val items = access.items.first()
        val mirrored = frame.mirrored
        val (bytes, limit) = itemSource(access)
        val expression = if (value.kind == ValueType.Collection.Kind.MAP) {
            val values = access.items[1]
            CodeBlock.of(
                "%T.map($bytes, first, $limit, count, %L, %L, %L, %L, %L, %L)",
                VIEW_COLLECTIONS,
                terminator,
                items.reference(),
                items.reference(),
                values.reference(),
                values.reference(),
                mirrored,
            )
        } else {
            val scanned = CodeBlock.of("%T.list($bytes, first, $limit, count, %L, %L, %L, %L)", VIEW_COLLECTIONS, terminator, items.reference(), items.reference(), mirrored)
            val stride = items.plan.staticSize
            if (stride != null && access.count !is Count.Terminated && access.count !is Count.Unmarked && access.count !is Count.Stuffed) {
                val fixed = CodeBlock.of(
                    "%T.of(b, first, lim, count, %L, %L, %L, $PARENT, $mirrored)",
                    FIXED_STRIDE_LIST,
                    stride,
                    items.reference(),
                    if (items.field.settable) items.reference() else CodeBlock.of("null"),
                )
                fixed
            } else {
                scanned
            }
        }
        val conversion = collectionConversion(value)
        if (conversion.isEmpty()) getter.addStatement("return %L", expression) else getter.addStatement("return (%L)%L", expression, conversion)
    }

    /** The items of a stuffed collection encoded one after the other, as the encoder builds them before stuffing them. */
    private fun stuffedContent(field: FieldPlan): FunSpec {
        val access = field.access as Access.Collection
        val value = field.value as ValueType.Collection
        val function = FunSpec.builder("contentOf${field.name.capitalized()}").addModifiers(KModifier.PRIVATE).addParameter("values", value.typeName).returns(BYTE_ARRAY)
        val (loop, parts) = if (value.kind == ValueType.Collection.Kind.MAP) {
            "for ((key, value) in values)" to listOf(access.items[0] to "key", access.items[1] to "value")
        } else {
            "for (item in values)" to listOf(access.items.single() to "item")
        }
        function.addStatement("var size = 0")
        function.beginControlFlow(loop)
        parts.forEach { (frame, item) -> function.addStatement("size += %T.sizeOfValues($item)", frame.objectName) }
        function.endControlFlow()
        function.addStatement("val b = %T(size)", BYTE_ARRAY)
        function.addStatement("var pos = 0")
        function.beginControlFlow(loop)
        parts.forEach { (frame, item) ->
            function.addStatement("pos = %T.writeValues(b, pos, b.size, $item)", frame.objectName)
        }
        function.endControlFlow()
        return function.addStatement("return b").build()
    }

    private fun collectionConversion(value: ValueType.Collection): String = when (value.kind) {
        ValueType.Collection.Kind.LIST, ValueType.Collection.Kind.MAP -> ""
        ValueType.Collection.Kind.SET -> ".toSet()"
        ValueType.Collection.Kind.ARRAY -> ".toTypedArray()"
        ValueType.Collection.Kind.PRIMITIVE_ARRAY -> ".to${(value.item.typeName as ClassName).simpleName}Array()"
    }

    private fun emptyCollection(value: ValueType.Collection): CodeBlock = when (value.kind) {
        ValueType.Collection.Kind.LIST -> CodeBlock.of("emptyList()")
        ValueType.Collection.Kind.SET -> CodeBlock.of("emptySet()")
        ValueType.Collection.Kind.MAP -> CodeBlock.of("emptyMap()")
        ValueType.Collection.Kind.ARRAY -> CodeBlock.of("emptyArray()")
        ValueType.Collection.Kind.PRIMITIVE_ARRAY -> CodeBlock.of("%T(0)", value.typeName.copy(nullable = false))
    }

    private fun collectionEnd(function: FunSpec.Builder, field: FieldPlan, access: Access.Collection, pos: CodeBlock, mirrored: Boolean) {
        access.emptyBit?.let { function.addStatement("if (!%T.bit(b, s, %L, lim)) return start", VIEW_BYTES, it) }
        function.addStatement("val pos = %L", pos)
        (access.count as? Count.Stuffed)?.let { count ->
            function.addStatement("return (%T.end(b, pos, lim, %N, %L) - s) * 8", VIEW_STUFFING, "${field.name}Stuffing", count.terminator.literal())
            return
        }
        function.collectionCount(field, access, mirrored)
        val stride = access.items.map { it.plan.staticSize }.takeIf { sizes -> sizes.all { it != null } }?.sumOf { it!! }
        val scanned = CodeBlock.of(
            "%T.%N(b, first, lim, count, %L, %L)",
            VIEW_COLLECTIONS,
            if (mirrored) "endDown" else "end",
            terminator(access),
            access.items.map { it.reference() }.joinToCode(", "),
        )
        val sign = if (mirrored) "-" else "+"
        val end = when {
            stride == null || access.count is Count.Terminated || access.count is Count.Unmarked -> scanned
            access.count is Count.Prefix -> CodeBlock.of("if (count >= 0) first $sign count * %L else %L", stride, scanned)
            else -> CodeBlock.of("first $sign count * %L", stride)
        }
        function.addStatement("val end = %L", end)
        val bits = if (mirrored) "(s - end) * 8" else "(end - s) * 8"
        // Without a count or terminator, an empty collection writes nothing and does not end a partly filled byte.
        if (access.count is Count.Flag || access.count is Count.Unmarked) {
            function.addStatement("return if (end == pos) start else $bits")
        } else {
            function.addStatement("return $bits")
        }
    }

    private fun walkCollection(walk: Walk, field: FieldPlan, access: Access.Collection, value: CodeBlock) {
        val collection = field.value as ValueType.Collection
        val name = field.name.capitalized()
        walk.goRuntime()
        val conditions = listOfNotNull(
            CodeBlock.of("%L != null", value).takeIf { field.nullable },
            CodeBlock.of("%L.isNotEmpty()", value).takeIf { access.emptyBit != null },
        )
        if (conditions.isNotEmpty()) walk.begin("if (%L)", conditions.joinToCode(" && "))
        access.emptyBit?.let { walk.statement("%T.setBit(b, s, %L, true, lim)", VIEW_BYTES, it) }
        // Without @NullIfEmpty a present collection is marked present even when it is empty.
        if (access.emptyBit == null) (field.presence as? Presence.Owned)?.let { walk.statement("%T.setBit(b, s, %L, true, lim)", VIEW_BYTES, it.bitPos) }
        val size = CodeBlock.of("%L.size", value)
        when (val count = access.count) {
            is Count.Prefix -> {
                walk.align()
                if (walk.dry) {
                    walk.code(CodeBlock.of("$BIT_CURSOR += %L.expectedByteSize(%L.toUInt()) * 8", endMarking(count.marking), size))
                } else if (walk.mirrored) {
                    walk.code(
                        CodeBlock.of(
                            "$BIT_CURSOR += %T.writeLengthPrefixDown(b, %L, %L, %L, %L) * 8",
                            VIEW_COLLECTIONS,
                            walk.bytePos,
                            size,
                            endMarking(count.marking),
                            order(count.order),
                        ),
                    )
                } else {
                    walk.code(
                        CodeBlock.of(
                            "$BIT_CURSOR += %T.writeLengthPrefix(b, %L, lim, %L, %L, %L) * 8",
                            VIEW_COLLECTIONS,
                            walk.bytePos,
                            size,
                            endMarking(count.marking),
                            order(count.order),
                        ),
                    )
                }
            }

            is Count.Number -> when (val width = count.width) {
                is Width.Fixed -> {
                    walk.align()
                    walk.statement(
                        "%T.writeNatural(b, %L, %L.toLong(), %L, false, %L, %L)",
                        VIEW_BYTES,
                        walk.location.start(width.length.bytes),
                        size,
                        length(width.length),
                        order(count.writeOrder),
                        if (walk.mirrored) "b.size" else "lim",
                    )
                    walk.advance(width.length.bytes * Byte.SIZE_BITS)
                }

                is Width.Selected -> {
                    walk.code(CodeBlock.of("val countIndexOf$name = %T.selectLengthIndex(%N, %L.toLong(), false)", NUMERIC_CODEC, "${field.name}CountLengths", size))
                    walk.code(CodeBlock.of("val countOf$name = %N[countIndexOf$name]", "${field.name}CountLengths"))
                    walk.statement("%T.setBits(b, s, %L, %L, countIndexOf$name.toLong(), lim)", VIEW_BYTES, width.bitPos, width.bits)
                    walk.align()
                    walk.statement("%T.writeNatural(b, %L, %L.toLong(), countOf$name, false, %L, lim)", VIEW_BYTES, walk.bytePos, size, order(count.writeOrder))
                    walk.advanceBytes(CodeBlock.of("countOf$name.bytes"))
                }
            }

            is Count.Flag -> walk.statement("%T.setBits(b, s, %L, %L, %L.toLong(), lim)", VIEW_BYTES, count.bitPos, count.bits, size)

            is Count.Terminated, is Count.Unmarked -> Unit

            is Count.Stuffed -> {
                walk.align()
                if (walk.dry) {
                    walk.code(CodeBlock.of("val contentOf$name = contentOf$name(%L)", value))
                    walk.code(CodeBlock.of("contents?.add(contentOf$name)"))
                    walk.code(CodeBlock.of("$BIT_CURSOR += %T.sizeOf(contentOf$name, %N) * 8", VIEW_STUFFING, "${field.name}Stuffing"))
                } else {
                    walk.code(CodeBlock.of("val contentOf$name = contents?.take() ?: contentOf$name(%L)", value))
                    walk.code(
                        CodeBlock.of(
                            "$BIT_CURSOR += %T.write(b, %L, lim, contentOf$name, %N, %L) * 8",
                            VIEW_STUFFING,
                            walk.bytePos,
                            "${field.name}Stuffing",
                            count.terminator.literal(),
                        ),
                    )
                }
                if (conditions.isNotEmpty()) walk.end()
                return
            }
        }
        val terminator = (access.count as? Count.Terminated)?.terminator
        val loopValues = if (collection.kind == ValueType.Collection.Kind.MAP) listOf("keyOf$name", "valueOf$name") else listOf("itemOf$name")
        if (terminator != null && !walk.dry) walk.code(CodeBlock.of("var indexOf$name = 0"))
        if (collection.kind ==
            ValueType.Collection.Kind.MAP
        ) {
            walk.begin("for ((${loopValues[0]}, ${loopValues[1]}) in %L)", value)
        } else {
            walk.begin("for (${loopValues[0]} in %L)", value)
        }
        access.items.forEachIndexed { index, frame ->
            val item = loopValues[index]
            val contents = contentsArgument(frame.plan.hasStuffed())
            val stride = frame.plan.staticSize
            walk.align()
            val end = if (stride != null || walk.dry) {
                walk.statement("%T.writeValues(b, %L, lim, $item$contents)", frame.objectName, walk.bytePos)
                null
            } else {
                "endOf${item.capitalized()}".also { walk.code(CodeBlock.of("val $it = %T.writeValues(b, %L, lim, $item$contents)", frame.objectName, walk.bytePos)) }
            }
            // Like the encoder, only a list item or a map key must not start with the terminator.
            if (terminator != null && index == 0) {
                if (walk.mirrored) {
                    // The decoder, reading from the end, meets an item's last byte in the array first.
                    walk.statement("%T.checkNotTerminator(b, %L - 1, %L, %L, indexOf$name++)", VIEW_COLLECTIONS, walk.bytePos, walk.bytePos, terminator.literal())
                } else {
                    val itemEnd = end?.let { CodeBlock.of(it) } ?: CodeBlock.of("%L + %L", walk.bytePos, stride ?: 0)
                    walk.statement("%T.checkNotTerminator(b, %L, %L, %L, indexOf$name++)", VIEW_COLLECTIONS, walk.bytePos, itemEnd, terminator.literal())
                }
            }
            when {
                end != null -> walk.code(CodeBlock.of(if (walk.mirrored) "$BIT_CURSOR = (s - $end) * 8" else "$BIT_CURSOR = ($end - s) * 8"))
                stride != null -> walk.advanceBytes(CodeBlock.of("%L", stride))
                else -> walk.advanceBytes(CodeBlock.of("%T.sizeOfValues($item$contents)", frame.objectName))
            }
        }
        walk.end()
        if (terminator != null) {
            walk.align()
            walk.statement("%T.write(b, %L, %N, %L)", VIEW_BYTES, walk.location.start(1), "${field.name}Terminator", if (walk.mirrored) "b.size" else "lim")
            walk.advance(Byte.SIZE_BITS)
        }
        if (conditions.isNotEmpty()) walk.end()
    }

    private fun collectionData(field: FieldPlan, access: Access.Collection, get: CodeBlock): CodeBlock {
        val value = field.value as ValueType.Collection
        fun convert(frame: ItemFrame, item: String): CodeBlock {
            val nested = frame.field.access as? Access.Nested ?: return CodeBlock.of(item)
            return if (frame.field.nullable) {
                CodeBlock.of(
                    "($item as %T?)?.toData()",
                    nested.context.sliceName,
                )
            } else {
                CodeBlock.of("($item as %T).toData()", nested.context.sliceName)
            }
        }
        val items = access.items.first()
        val copy = when (value.kind) {
            ValueType.Collection.Kind.LIST -> CodeBlock.of("it.map { item -> %L }", convert(items, "item"))
            ValueType.Collection.Kind.SET -> CodeBlock.of("it.map { item -> %L }.toSet()", convert(items, "item"))
            ValueType.Collection.Kind.ARRAY -> CodeBlock.of("it.map { item -> %L }.toTypedArray()", convert(items, "item"))
            ValueType.Collection.Kind.PRIMITIVE_ARRAY -> CodeBlock.of("it")
            ValueType.Collection.Kind.MAP -> CodeBlock.of("it.entries.associate { (key, value) -> %L to %L }", convert(items, "key"), convert(access.items[1], "value"))
        }
        return CodeBlock.of(if (field.nullable) "%L?.let { %L }" else "%L.let { %L }", get, copy)
    }

    private fun bufferFunction(name: String, leading: String? = null): FunSpec.Builder = FunSpec.builder(name)
        .apply { if (leading != null) addParameter(leading, STRING) }
        .addParameter("b", BYTE_ARRAY)
        .addParameter("s", INT)
        .addParameter("lim", INT)

    private fun constants(field: FieldPlan): List<PropertySpec> {
        val name = field.name
        val access = field.access.unframed()
        return when (access) {
            is Access.EnumTable -> listOfNotNull(
                PropertySpec.builder("${name}Table", ARRAY.parameterizedBy(BYTE_ARRAY), KModifier.PRIVATE)
                    .initializer("arrayOf(%L)", access.table.map { it.literal() }.joinToCode(", "))
                    .build(),
                access.prefix?.let { byteArrayConstant("${name}Prefix", it) },
                access.postfix?.let { byteArrayConstant("${name}Postfix", it) },
            )

            is Access.Collection -> listOfNotNull(
                ((access.count as? Count.Number)?.width as? Width.Selected)?.let { width ->
                    PropertySpec.builder("${name}CountLengths", ARRAY.parameterizedBy(LENGTH), KModifier.PRIVATE)
                        .initializer("%L", width.lengths.map { length(it) }.joinToCode(", ", prefix = "arrayOf(", suffix = ")"))
                        .build()
                },
                (access.count as? Count.Terminated)?.let { byteArrayConstant("${name}Terminator", byteArrayOf(it.terminator)) },
                (access.count as? Count.Stuffed)?.let { PropertySpec.builder("${name}Stuffing", STUFFING_SCHEME, KModifier.PRIVATE).initializer("%L", scheme(it.scheme)).build() },
            )

            is Access.Text -> listOf(
                PropertySpec.builder("${name}String", STRING_SETTINGS, KModifier.PRIVATE)
                    .initializer("%T(%L, %T.%N)", STRING_SETTINGS, endMarking(access.endMarking), ENCODING, access.encoding.name)
                    .build(),
            )

            is Access.Number -> listOfNotNull(
                access.settings.constant()?.let { PropertySpec.builder("${name}Settings", it.first, KModifier.PRIVATE).initializer(it.second).build() },
                (access.width as? Width.Selected)?.takeIf { it.kind == Width.Selected.Kind.INDEX }?.let { width ->
                    PropertySpec.builder("${name}Lengths", ARRAY.parameterizedBy(LENGTH), KModifier.PRIVATE)
                        .initializer("%L", width.lengths.map { length(it) }.joinToCode(", ", prefix = "arrayOf(", suffix = ")"))
                        .build()
                },
            )

            else -> emptyList()
        } + (
            (field.access as? Access.Framed)?.let { framed ->
                listOfNotNull(
                    framed.prefix?.let { byteArrayConstant("${name}FramePrefix", it) },
                    framed.postfix?.let { byteArrayConstant("${name}FramePostfix", it) },
                    framed.checksum?.let { checksumConstant("${name}Checksum", it) },
                )
            } ?: emptyList()
            )
    }

    private fun byteArrayConstant(name: String, bytes: ByteArray) = PropertySpec.builder(name, BYTE_ARRAY, KModifier.PRIVATE).initializer("%L", bytes.literal()).build()

    private fun dataValue(field: FieldPlan): CodeBlock {
        val get = CodeBlock.of("get${field.name.capitalized()}(b, s, lim)")
        (field.access as? Access.Collection)?.let { return collectionData(field, it, get) }
        (field.access as? Access.Sealed)?.let { sealed ->
            // A sealed DATA interface does not extend its layout interface; every one of its implementations does.
            val type = sealed.context.layout.interfaceClassName
            return if (field.nullable) {
                CodeBlock.of("%L?.let { %T.toData(it) as %T }", get, sealed.context.layoutName, type)
            } else {
                CodeBlock.of("%T.toData(%L) as %T", sealed.context.layoutName, get, type)
            }
        }
        val access = field.access as? Access.Nested ?: return get
        return if (field.nullable) {
            CodeBlock.of("(%L as %T?)?.toData()", get, access.context.sliceName)
        } else {
            CodeBlock.of("(%L as %T).toData()", get, access.context.sliceName)
        }
    }

    /** The limit a nested frame at [pos] reads up to: its own end when that is fixed, else its parent's minus its postfix. */
    private fun nestedLimit(access: Access.Nested, pos: CodeBlock): CodeBlock {
        val plan = access.context.plan!!.getOrThrow()
        val size = plan.staticSize
        return when {
            size != null -> CodeBlock.of("%L + %L", pos, size - plan.footer)
            plan.footer == 0 -> CodeBlock.of("lim")
            else -> CodeBlock.of("lim - %L", plan.footer)
        }
    }

    private fun fixedContentBytes(access: Access): Int = when (access) {
        is Access.Number -> (access.width as Width.Fixed).length.bytes

        is Access.Character -> access.encoding.byteSize

        is Access.Text -> access.fixedBytes ?: error("$access has no fixed body size")

        is Access.EnumTable -> access.fixedBytes ?: error("$access has no fixed body size")

        is Access.BodyBit -> 1

        // Flag bits a value class wraps live in its parent's flag header, not inside its frame.
        is Access.HeaderBit, is Access.PackedNumber, is Access.PackedEnum -> 0

        is Access.Framed -> (access.prefix?.size ?: 0) + fixedContentBytes(access.inner) + (access.checksum?.crc?.byteWidth ?: 0) + (access.postfix?.size ?: 0)

        else -> error("$access has no fixed body size")
    }

    /** The body bytes of [access], read from the flag header when they depend on it. */
    private fun contentBytes(field: FieldPlan, access: Access): CodeBlock {
        val width = (access as? Access.Number)?.width as? Width.Selected ?: return CodeBlock.of("%L", fixedContentBytes(access))
        return when (width.kind) {
            Width.Selected.Kind.INDEX -> CodeBlock.of(
                "%T.selectedLength(%N, %T.bits(b, s, %L, %L, lim).toInt()).bytes",
                VIEW_BYTES,
                "${field.name}Lengths",
                VIEW_BYTES,
                width.bitPos,
                width.bits,
            )

            Width.Selected.Kind.LARGER -> CodeBlock.of(
                "(if (%T.bit(b, s, %L, lim)) %L else %L)",
                VIEW_BYTES,
                width.bitPos,
                width.lengths.last().bytes,
                width.lengths.first().bytes,
            )
        }
    }

    private fun read(field: FieldPlan, access: Access, location: Location): CodeBlock = when (access) {
        is Access.Nested -> CodeBlock.of("%T(b, %L, %L, $PARENT)", access.context.sliceName, location.pos, nestedLimit(access, location.pos))

        is Access.Sealed -> CodeBlock.of("%T.getValue(b, %L, %L, $PARENT)", access.context.layoutName, location.pos, sealedLimit(access))

        is Access.Framed -> read(
            field,
            access.inner,
            if (access.inner is Access.BodyBit) {
                Location(location.plus(access.prefix?.size ?: 0).pos, CodeBlock.of("0"))
            } else {
                location.plus(access.prefix?.size ?: 0)
            },
        )

        else -> wrap(field.value, readLeaf(field, access, location))
    }

    /** Reads a value of a mirrored frame, which ends at `location.pos`; bounds are those of the array. */
    private fun readMirrored(field: FieldPlan, access: Access, location: Location): CodeBlock {
        val leaf = field.value.leaf()
        val kind = field.value.leafKind
        return when (access) {
            is Access.Number -> readNumber(field, access, kind, location.start((access.width as Width.Fixed).length.bytes), "b.size")

            is Access.Character -> CodeBlock.of(
                "%T.readChar(b, %L, %T.%N, %L, b.size)",
                VIEW_BYTES,
                location.start(access.encoding.byteSize),
                ENCODING,
                access.encoding.name,
                order(access.readOrder),
            )

            is Access.EnumTable -> CodeBlock.of(
                "%T.entries[%T.matchIndex(b, %L, %N, b.size)]",
                leaf.typeName,
                VIEW_BYTES,
                location.plus(access.prefix?.size ?: 0).start(access.table.first().size),
                "${field.name}Table",
            )

            is Access.Text -> CodeBlock.of("%T.readDown(b, %L, lim, %N)", VIEW_STRINGS, location.pos, "${field.name}String")

            else -> error("$access is not planned in a mirrored frame")
        }
    }

    /** Writes a value of a mirrored frame ending at `location.pos`, as the encoder prepends it. */
    private fun writeMirrored(field: FieldPlan, access: Access, location: Location, value: CodeBlock): List<CodeBlock> {
        val kind = field.value.leafKind
        val name = field.name
        return when (access) {
            is Access.Number -> listOf(writeNumber(field, access, kind, location.start((access.width as Width.Fixed).length.bytes), value, "b.size"))

            is Access.Character -> listOf(
                CodeBlock.of(
                    "%T.writeChar(b, %L, %L, %T.%N, %L, b.size)",
                    VIEW_BYTES,
                    location.start(access.encoding.byteSize),
                    value,
                    ENCODING,
                    access.encoding.name,
                    order(access.writeOrder),
                ),
            )

            is Access.EnumTable -> {
                val prefix = access.prefix?.size ?: 0
                val size = access.table.first().size
                listOfNotNull(
                    access.prefix?.let { CodeBlock.of("%T.write(b, %L, %N, b.size)", VIEW_BYTES, location.start(prefix), "${name}Prefix") },
                    CodeBlock.of("%T.write(b, %L, %N[%L.ordinal], b.size)", VIEW_BYTES, location.plus(prefix).start(size), "${name}Table", value),
                    access.postfix?.let { CodeBlock.of("%T.write(b, %L, %N, b.size)", VIEW_BYTES, location.plus(prefix + size).start(it.size), "${name}Postfix") },
                )
            }

            is Access.Text -> listOfNotNull(
                access.fixedBytes?.let { CodeBlock.of("%T.clear(b, %L, %L)", VIEW_BYTES, location.start(it), location.pos) },
                CodeBlock.of("%T.writeDown(b, %L, %L, %N, %L)", VIEW_STRINGS, location.pos, value, "${name}String", order(access.writeOrder)),
            )

            else -> error("$access is not planned in a mirrored frame")
        }
    }

    private fun readLeaf(field: FieldPlan, access: Access, location: Location): CodeBlock {
        if (location.mirrored) return readMirrored(field, access, location)
        val leaf = field.value.leaf()
        val kind = field.value.leafKind
        val pos = location.pos
        return when (access) {
            is Access.HeaderBit -> CodeBlock.of("%T.bit(b, s, %L, lim)", VIEW_BYTES, access.bitPos)

            is Access.BodyBit -> CodeBlock.of("%T.bit(b, %L, %L, lim)", VIEW_BYTES, pos, location.bit!!)

            is Access.PackedNumber -> CodeBlock.of("%T.packedNatural(b, s, %L, %L, %L, lim)%L", VIEW_BYTES, access.bitPos, access.bits, access.signed, fromLong(kind))

            is Access.PackedEnum -> CodeBlock.of(
                "%T.entry(%T.entries, %T.bits(b, s, %L, %L, lim).toInt(), %S)",
                VIEW_BYTES,
                leaf.typeName,
                VIEW_BYTES,
                access.bitPos,
                access.bits,
                (leaf as ValueType.Enumeration).serialName,
            )

            is Access.EnumTable -> CodeBlock.of(
                "%T.entries[%T.matchIndex(b, %L, %N, lim)]",
                leaf.typeName,
                VIEW_BYTES,
                location.plus(access.prefix?.size ?: 0).pos,
                "${field.name}Table",
            )

            is Access.Character -> CodeBlock.of("%T.readChar(b, %L, %T.%N, %L, lim)", VIEW_BYTES, pos, ENCODING, access.encoding.name, order(access.readOrder))

            is Access.Text -> CodeBlock.of("%T.read(b, %L, lim, %N)", VIEW_STRINGS, pos, "${field.name}String")

            is Access.Number -> readNumber(field, access, kind, pos)

            is Access.Nested, is Access.Framed, is Access.Collection, is Access.Sealed -> error("Read through read()")
        }
    }

    private fun readNumber(field: FieldPlan, access: Access.Number, kind: TypeKind, pos: CodeBlock, bound: String = "lim"): CodeBlock {
        val settings = CodeBlock.of("%N", "${field.name}Settings")
        val order = order(access.readOrder)
        val length = when (val width = access.width) {
            is Width.Fixed -> length(width.length)
            is Width.Selected -> CodeBlock.of("%T.selectedLength(%N, %T.bits(b, s, %L, %L, lim).toInt())", VIEW_BYTES, "${field.name}Lengths", VIEW_BYTES, width.bitPos, width.bits)
        }

        // For a selected floating point width, the flag bit picks the larger of the two sizes, both read at one position.
        fun larger(block: (Length, CodeBlock) -> CodeBlock): CodeBlock = when (val width = access.width) {
            is Width.Fixed -> block(width.length, pos)

            is Width.Selected -> CodeBlock.of(
                "(%L).let { at -> if (%T.bit(b, s, %L, lim)) %L else %L }",
                pos,
                VIEW_BYTES,
                width.bitPos,
                block(width.lengths.last(), CodeBlock.of("at")),
                block(width.lengths.first(), CodeBlock.of("at")),
            )
        }
        return when (val s = access.settings) {
            is NumericSettings.Natural -> CodeBlock.of("%T.readNatural(b, %L, %L, %L, %L, $bound)%L", VIEW_BYTES, pos, length, s.signed, order, fromLong(kind))

            is NumericSettings.Scalar -> CodeBlock.of(
                "%T.scalarFromWire(%L, %T.readNatural(b, %L, %L, %L, %L, $bound))%L",
                NUMERIC_CODEC,
                settings,
                VIEW_BYTES,
                pos,
                length,
                s.signed,
                order,
                fromDouble(kind),
            )

            is NumericSettings.RangeEncoded -> CodeBlock.of(
                "%T.rangeFromWire(%L, %T.readNatural(b, %L, %L, false, %L, $bound))%L",
                NUMERIC_CODEC,
                settings,
                VIEW_BYTES,
                pos,
                length,
                order,
                fromDouble(kind),
            )

            is NumericSettings.Decimal -> CodeBlock.of(
                "%L%L",
                larger { length, at ->
                    if (length == Length.`32_BIT`) {
                        CodeBlock.of("%T.readFloat(b, %L, %L, $bound).toDouble()", VIEW_BYTES, at, order)
                    } else {
                        CodeBlock.of("%T.readDouble(b, %L, %L, $bound)", VIEW_BYTES, at, order)
                    }
                },
                fromDouble(kind),
            )

            is NumericSettings.MedFloat -> CodeBlock.of(
                "%L%L",
                larger { length, at -> CodeBlock.of("%T.%N(b, %L, $bound)", VIEW_BYTES, if (length == Length.`16_BIT`) "readMedFloat16" else "readMedFloat32", at) },
                fromDouble(kind),
            )
        }
    }

    /** Writes a property of a fixed size at [location]. */
    private fun write(field: FieldPlan, access: Access, location: Location, value: CodeBlock): List<CodeBlock> {
        if (location.mirrored) return writeMirrored(field, access, location, value)
        val kind = field.value.leafKind
        val name = field.name
        val pos = location.pos
        return when (access) {
            is Access.Collection, is Access.Sealed -> error("${access::class.simpleName} is not written in place")

            is Access.HeaderBit -> listOf(CodeBlock.of("%T.setBit(b, s, %L, %L, lim)", VIEW_BYTES, access.bitPos, value))

            is Access.BodyBit -> listOf(CodeBlock.of("%T.setBit(b, %L, %L, %L, lim)", VIEW_BYTES, pos, location.bit!!, value))

            is Access.PackedNumber -> listOf(
                CodeBlock.of("%T.setPackedNatural(b, s, %L, %L, %L, %L, lim)", VIEW_BYTES, access.bitPos, access.bits, toLong(kind, value, !access.signed), access.signed),
            )

            is Access.PackedEnum -> listOf(CodeBlock.of("%T.setBits(b, s, %L, %L, %L.ordinal.toLong(), lim)", VIEW_BYTES, access.bitPos, access.bits, value))

            is Access.EnumTable -> listOfNotNull(
                access.prefix?.let { CodeBlock.of("%T.write(b, %L, %N, lim)", VIEW_BYTES, pos, "${name}Prefix") },
                CodeBlock.of("%T.write(b, %L, %N[%L.ordinal], lim)", VIEW_BYTES, location.plus(access.prefix?.size ?: 0).pos, "${name}Table", value),
                access.postfix?.let {
                    CodeBlock.of("%T.write(b, %L, %N, lim)", VIEW_BYTES, location.plus((access.prefix?.size ?: 0) + access.table.first().size).pos, "${name}Postfix")
                },
            )

            is Access.Character -> listOf(
                CodeBlock.of("%T.writeChar(b, %L, %L, %T.%N, %L, lim)", VIEW_BYTES, pos, value, ENCODING, access.encoding.name, order(access.writeOrder)),
            )

            is Access.Number -> listOf(writeNumber(field, access, kind, pos, value))

            // A shorter fixed length string leaves the rest of its bytes as they were, so clear them first.
            is Access.Text -> listOfNotNull(
                access.fixedBytes?.let { CodeBlock.of("%T.clear(b, %L, %L + %L)", VIEW_BYTES, pos, pos, it) },
                CodeBlock.of("%T.write(b, %L, lim, %L, %N, %L)", VIEW_STRINGS, pos, value, "${name}String", order(access.writeOrder)),
            )

            is Access.Nested -> {
                val plan = access.context.plan!!.getOrThrow()
                listOf(CodeBlock.of("%T.write(b, %L, %L, %L)", access.context.layoutName, pos, CodeBlock.of("%L + %L", pos, plan.staticSize!! - plan.footer), value))
            }

            is Access.Framed -> {
                val prefix = access.prefix?.size ?: 0
                val inner = if (access.inner is Access.BodyBit) Location(location.plus(prefix).pos, CodeBlock.of("0")) else location.plus(prefix)
                val innerEnd = prefix + fixedContentBytes(access.inner)
                listOfNotNull(access.prefix?.let { CodeBlock.of("%T.write(b, %L, %N, lim)", VIEW_BYTES, pos, "${name}FramePrefix") }) +
                    write(field, access.inner, inner, value) +
                    listOfNotNull(
                        access.checksum?.let {
                            CodeBlock.of(
                                "%T.update(b, %L, %L, %N, %L, lim)",
                                VIEW_CHECKSUM,
                                location.plus(prefix).pos,
                                location.plus(innerEnd).pos,
                                "${name}Checksum",
                                order(access.checksumOrder),
                            )
                        },
                        access.postfix?.let {
                            CodeBlock.of("%T.write(b, %L, %N, lim)", VIEW_BYTES, location.plus(innerEnd + (access.checksum?.crc?.byteWidth ?: 0)).pos, "${name}FramePostfix")
                        },
                    )
            }
        }
    }

    private fun writeNumber(field: FieldPlan, access: Access.Number, kind: TypeKind, pos: CodeBlock, value: CodeBlock, bound: String = "lim"): CodeBlock {
        val fixed = (access.width as Width.Fixed).length
        val length = length(fixed)
        val settings = CodeBlock.of("%N", "${field.name}Settings")
        return when (val s = access.settings) {
            is NumericSettings.Natural -> CodeBlock.of(
                "%T.writeNatural(b, %L, %L, %L, %L, %L, $bound)",
                VIEW_BYTES,
                pos,
                toLong(kind, value, !s.signed),
                length,
                s.signed,
                order(access.writeOrder),
            )

            is NumericSettings.Scalar -> CodeBlock.of(
                "%T.writeNatural(b, %L, %T.scalarToWire(%L, %L), %L, %L, %L, $bound)",
                VIEW_BYTES,
                pos,
                NUMERIC_CODEC,
                settings,
                encoderNumber(kind, value, !s.signed),
                length,
                s.signed,
                order(access.writeOrder),
            )

            is NumericSettings.RangeEncoded -> CodeBlock.of(
                "%T.writeNatural(b, %L, %T.rangeToWire(%L, %L), %L, false, %L, $bound)",
                VIEW_BYTES,
                pos,
                NUMERIC_CODEC,
                settings,
                value,
                length,
                order(access.writeOrder),
            )

            is NumericSettings.Decimal -> if (fixed == Length.`32_BIT`) {
                CodeBlock.of("%T.writeFloat(b, %L, %L.toFloat(), %L, $bound)", VIEW_BYTES, pos, value, order(access.writeOrder))
            } else {
                CodeBlock.of("%T.writeDouble(b, %L, %L.toDouble(), %L, $bound)", VIEW_BYTES, pos, value, order(access.writeOrder))
            }

            is NumericSettings.MedFloat -> CodeBlock.of(
                "%T.%N(b, %L, %L.toDouble(), $bound)",
                VIEW_BYTES,
                if (fixed == Length.`16_BIT`) "writeMedFloat16" else "writeMedFloat32",
                pos,
                value,
            )
        }
    }

    // BytesFormat widens an unsigned Byte, Short or Int before encoding it, so its bits are not sign-extended.
    private fun encoderNumber(kind: TypeKind, value: CodeBlock, unsigned: Boolean): CodeBlock = when {
        !unsigned -> value
        kind == TypeKind.BYTE -> CodeBlock.of("%L.toUByte().toShort()", value)
        kind == TypeKind.SHORT -> CodeBlock.of("%L.toUShort().toInt()", value)
        kind == TypeKind.INT -> CodeBlock.of("%L.toUInt().toLong()", value)
        else -> value
    }

    private fun toLong(kind: TypeKind, value: CodeBlock, unsigned: Boolean): CodeBlock = when {
        unsigned && kind == TypeKind.BYTE -> CodeBlock.of("%L.toUByte().toLong()", value)
        unsigned && kind == TypeKind.SHORT -> CodeBlock.of("%L.toUShort().toLong()", value)
        unsigned && kind == TypeKind.INT -> CodeBlock.of("%L.toUInt().toLong()", value)
        kind == TypeKind.LONG -> value
        else -> CodeBlock.of("%L.toLong()", value)
    }

    private fun fromLong(kind: TypeKind): String = when (kind) {
        TypeKind.BYTE -> ".toByte()"
        TypeKind.SHORT -> ".toShort()"
        TypeKind.INT -> ".toInt()"
        TypeKind.FLOAT -> ".toDouble().toFloat()"
        TypeKind.DOUBLE -> ".toDouble()"
        else -> ""
    }

    private fun fromDouble(kind: TypeKind): String = when (kind) {
        TypeKind.BYTE -> ".toInt().toByte()"
        TypeKind.SHORT -> ".toInt().toShort()"
        TypeKind.INT -> ".toInt()"
        TypeKind.LONG -> ".toLong()"
        TypeKind.FLOAT -> ".toFloat()"
        else -> ""
    }

    private fun wrap(value: ValueType, leaf: CodeBlock): CodeBlock = when (value) {
        is ValueType.Unsigned -> CodeBlock.of("%L.to%L()", leaf, (value.typeName as ClassName).simpleName)
        is ValueType.Wrapped -> CodeBlock.of("%T(%L)", value.constructor, wrap(value.inner, leaf))
        else -> leaf
    }

    private fun unwrap(value: ValueType, expression: CodeBlock): CodeBlock = when (value) {
        is ValueType.Unsigned -> CodeBlock.of("%L.to%L()", expression, (value.signed.typeName as ClassName).simpleName)
        is ValueType.Wrapped -> unwrap(value.inner, CodeBlock.of("%L.%N", expression, value.propertyName))
        else -> expression
    }

    private fun ValueType.leaf(): ValueType = when (this) {
        is ValueType.Unsigned -> signed
        is ValueType.Wrapped -> inner.leaf()
        else -> this
    }

    private fun Access.unframed(): Access = if (this is Access.Framed) inner.unframed() else this

    private fun at(pos: Int): CodeBlock = if (pos == 0) CodeBlock.of("s") else CodeBlock.of("s + %L", pos)

    private fun length(length: Length): CodeBlock = CodeBlock.of("%T.%N", LENGTH, length.name)

    private fun order(order: ByteOrder): CodeBlock = CodeBlock.of("%T.%N", BYTE_ORDER, order.name)

    private fun endMarking(endMarking: StringEncodingSettings.EndMarking): CodeBlock = when (endMarking) {
        is StringEncodingSettings.LengthPrefix.ByteLength -> CodeBlock.of("%T.ByteLength", LENGTH_PREFIX)
        is StringEncodingSettings.LengthPrefix.ShortLength -> CodeBlock.of("%T.ShortLength", LENGTH_PREFIX)
        is StringEncodingSettings.LengthPrefix.WithOverflow -> CodeBlock.of("%T.WithOverflow(%L)", LENGTH_PREFIX, endMarking.sentinel.literal())
        is StringEncodingSettings.NullTerminated -> CodeBlock.of("%T.NullTerminated", STRING_SETTINGS)
        is StringEncodingSettings.NoMarking -> CodeBlock.of("%T.NoMarking", STRING_SETTINGS)
        is StringEncodingSettings.FixedLength -> CodeBlock.of("%T.FixedLength(%L)", STRING_SETTINGS, endMarking.length)
        is StringEncodingSettings.Terminated -> CodeBlock.of("%T.Terminated(%L)", STRING_SETTINGS, endMarking.terminator.literal())
        is StringEncodingSettings.ByteStuffed.Delimited -> CodeBlock.of("%T.Delimited(%L)", BYTE_STUFFED, scheme(endMarking.scheme))
        is StringEncodingSettings.ByteStuffed.Explicit -> CodeBlock.of("%T.Explicit(%L, %L)", BYTE_STUFFED, scheme(endMarking.scheme), endMarking.terminator.literal())
    }

    private fun scheme(scheme: ByteStuffingScheme): CodeBlock = when (scheme) {
        is ByteStuffingScheme.CSafe -> CodeBlock.of("%T(%L, %L)", STUFFING_SCHEME.nestedClass("CSafe"), scheme.escapeByte.literal(), scheme.mask.literal())

        is ByteStuffingScheme.Xor -> CodeBlock.of(
            "%T(%L, %L, %L, %L)",
            STUFFING_SCHEME.nestedClass("Xor"),
            scheme.escapeByte.literal(),
            scheme.delimiter.literal(),
            scheme.additionalEscapedBytes.joinToString(", ", prefix = "setOf<Byte>(", postfix = ")") { it.literal() },
            scheme.xorKey.literal(),
        )

        is ByteStuffingScheme.Slip -> CodeBlock.of(
            "%T(%L, %L, %L, %L)",
            STUFFING_SCHEME.nestedClass("Slip"),
            scheme.end.literal(),
            scheme.escapeByte.literal(),
            scheme.escapedEnd.literal(),
            scheme.escapedEsc.literal(),
        )

        is ByteStuffingScheme.Cobs -> CodeBlock.of("%T", STUFFING_SCHEME.nestedClass("Cobs"))
    }

    private fun NumericSettings.constant(): Pair<ClassName, CodeBlock>? {
        val lengths = supportedLengths.map { length(it) }.joinToCode(", ", prefix = "setOf(", suffix = ")")
        return when (this) {
            is NumericSettings.Scalar -> NUMERIC_SETTINGS.nestedClass("Scalar") to
                CodeBlock.of("%T(%L, %L, %L, %L, %L, %L)", NUMERIC_SETTINGS.nestedClass("Scalar"), lengths, signed, multiplier, decimalExponent, binaryExponent, offset)

            is NumericSettings.RangeEncoded -> NUMERIC_SETTINGS.nestedClass("RangeEncoded") to
                CodeBlock.of("%T(%L, %L, %L)", NUMERIC_SETTINGS.nestedClass("RangeEncoded"), lengths, min.literal(), max.literal())

            else -> null
        }
    }

