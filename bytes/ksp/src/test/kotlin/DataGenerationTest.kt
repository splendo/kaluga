package com.splendo.kaluga.bytes.ksp

import com.tschuchort.compiletesting.KotlinCompilation
import org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

@OptIn(ExperimentalCompilerApi::class)
class DataGenerationTest {

    @Test
    fun `generates a serializable data class implementing the layout`() {
        val compilation = BytesCompilation(
            layoutSource(
                """
                @BytesLayout
                interface Header {
                    @Size(Length.`8_BIT`)
                    @Unsigned
                    val version: Int
                }

                @BytesLayout
                @Prefix([0x01, 0xAA.toByte()])
                interface Reading : Header {
                    @Size(Length.`8_BIT`)
                    @Size(Length.`16_BIT`)
                    val value: Int
                    val label: String?
                    val headers: List<Header>
                }
                """,
            ),
        )

        assertEquals(KotlinCompilation.ExitCode.OK, compilation.result.exitCode, compilation.result.messages)
        assertEquals(
            """
            // Generated by the Kaluga bytes KSP processor from test.Reading. Do not edit.
            package test

            import com.splendo.kaluga.bytes.annotations.Length
            import com.splendo.kaluga.bytes.annotations.Prefix
            import com.splendo.kaluga.bytes.annotations.Size
            import com.splendo.kaluga.bytes.annotations.Unsigned
            import kotlin.Int
            import kotlin.String
            import kotlin.collections.List
            import kotlinx.serialization.KSerializer
            import kotlinx.serialization.SerialName
            import kotlinx.serialization.Serializable
            import kotlinx.serialization.descriptors.SerialDescriptor
            import kotlinx.serialization.encoding.Decoder
            import kotlinx.serialization.encoding.Encoder

            /**
             * The `BytesFormat` DATA implementation of [Reading].
             */
            @Serializable
            @SerialName("test.Reading")
            @Prefix(`value` = [0x01.toByte(), 0xAA.toByte()])
            public data class ReadingData(
                @Size(length = Length.`8_BIT`)
                @Unsigned
                override val version: Int,
                @Size(length = Length.`8_BIT`)
                @Size(length = Length.`16_BIT`)
                override val `value`: Int,
                override val label: String?,
                override val headers: List<@Serializable(with = HeaderData.InterfaceSerializer::class) Header>,
            ) : Reading {
                public companion object {
                    /**
                     * The layout of [Reading] as computed at compile time; `layoutDumpOf(serializer().descriptor)` must return the same.
                     */
                    internal const val LAYOUT_DUMP: String =
                            "0 test.Reading: struct order=LSB/LSB prefix=01 aa header=2 static=?\n  0 version: natural(8 unsigned) order=LSB/LSB bytes=1\n  1 value: natural(8,16 signed) order=LSB/LSB bits=0+1 bytes=?\n  2 label: string(UTF_8 prefix8) order=LSB/LSB bits=1+1 nullable bytes=?\n  3 headers: list(count(8)) order=LSB/LSB bytes=?\n    0 0: struct order=LSB/LSB bytes=1\n      0 version: natural(8 unsigned) order=LSB/LSB bytes=1\n"

                    /**
                     * Returns [value] as a [ReadingData], copying it when it is another implementation of [Reading].
                     */
                    public fun from(`value`: Reading): ReadingData = value as? ReadingData ?: ReadingData(version = value.version, `value` = value.`value`, label = value.label, headers = value.headers)
                }

                /**
                 * Serializes any [Reading] through the [ReadingData] serializer.
                 */
                public object InterfaceSerializer : KSerializer<Reading> {
                    override val descriptor: SerialDescriptor = ReadingData.serializer().descriptor

                    override fun serialize(encoder: Encoder, `value`: Reading) {
                        ReadingData.serializer().serialize(encoder, ReadingData.from(value))
                    }

                    override fun deserialize(decoder: Decoder): Reading = ReadingData.serializer().deserialize(decoder)
                }
            }

            """.trimIndent(),
            compilation.generatedFile("ReadingData.kt"),
        )

        val readingData = compilation.result.classLoader.loadClass("test.ReadingData")
        assertTrue(compilation.result.classLoader.loadClass("test.Reading").isAssignableFrom(readingData))
    }

    @Test
    fun `generates a sealed data interface without extending the sealed layout`() {
        val compilation = BytesCompilation(
            layoutSource(
                """
                @BytesLayout
                sealed interface Command

                @BytesLayout
                @SerializedByteValue(0x02)
                interface Stop : Command

                @BytesLayout
                @SerializedByteValue(0x01)
                interface Start : Command {
                    val speed: Byte
                }

                // Still exhaustive: the generated sealed CommandData is not a subtype of Command.
                fun describe(command: Command): String = when (command) {
                    is Start -> "start"
                    is Stop -> "stop"
                }
                """,
            ),
        )

        assertEquals(KotlinCompilation.ExitCode.OK, compilation.result.exitCode, compilation.result.messages)
        val generated = compilation.generatedFile("CommandData.kt")
        assertTrue("public sealed interface CommandData {" in generated, generated)
        assertTrue("public data class StartData(\n    override val speed: Byte,\n) : Start,\n    CommandData {" in generated, generated)
        assertTrue("public data object StopData : Stop, CommandData {" in generated, generated)
        // Start and Stop are generated in the sealed root's file only.
        assertEquals(listOf("CommandData.kt", "GeneratedBytesLayouts.kt"), compilation.generatedFiles.map { it.name }.sorted())
    }

    @Test
    fun `generates no DATA for a VIEW-only layout`() {
        val compilation = BytesCompilation(
            layoutSource(
                """
                @BytesLayout(generate = [Generate.VIEW])
                interface OnlyView {
                    val value: Byte
                }
                """,
            ),
        )

        assertEquals(KotlinCompilation.ExitCode.OK, compilation.result.exitCode, compilation.result.messages)
        assertEquals(listOf("OnlyViewView.kt"), compilation.generatedFiles.map { it.name })
    }
}
